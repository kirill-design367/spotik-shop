import type { ReactNode } from 'react';

/**
 * Данные, которые переводчик браузера трогать не имеет права.
 *
 * ⚠️ ПЕРЕВОДЧИК ПЕРЕПИСЫВАЕТ НЕ ТОЛЬКО СЛОВА. Помощник открывал русскую
 * админку браузером, который сам переводит страницу, — и почта клиента
 * «aairatttttttt@gmail.com» вышла у него с другим числом «t»: машинный
 * перевод не отличает адрес от слова. Пароли и почты аккаунтов оператор
 * вводит в Spotify руками, и на них та же беда — это аккаунт не на ту
 * почту и пароль, который не подойдёт (Р-166).
 *
 * Поэтому всё, что ввёл человек — почты, пароли, коды, метки кампании, —
 * стоит под `translate="no"`, а надписи вокруг переводятся как раньше.
 * Класс `notranslate` рядом не для красоты: атрибут — стандарт, его
 * понимают Chrome, Safari, Firefox и Edge, а класс — давний договор
 * переводчика Google, и одного из двух какой-нибудь браузер может
 * не знать.
 */
export default function Bukvalno({ children, className }: { children: ReactNode; className?: string }) {
  return (
    <span translate="no" className={className ? `notranslate ${className}` : 'notranslate'}>
      {children}
    </span>
  );
}

/** То же для элемента, у которого уже есть своя разметка: `<dd {...NE_PEREVODIT}>`. */
export const NE_PEREVODIT = { translate: 'no', className: 'notranslate' } as const;

/**
 * Значение под защитой, а пустое — надписью. Надпись («стёрто»,
 * «покупатель», прочерк) — наша, и переводить её можно; защищать
 * её вместе с данными значило бы оставить кусок экрана непереведённым
 * без всякой причины.
 */
export function iliNadpis(v: string | null | undefined, nadpis: ReactNode): ReactNode {
  return v == null ? nadpis : <Bukvalno>{v}</Bukvalno>;
}

/**
 * Строка, разрезанная на куски: нечётные — данные, чётные — надпись.
 *
 * ⚠️ ЦЕЛИКОМ ОДНИМ ЭЛЕМЕНТОМ, И КАЖДЫЙ КУСОК НАДПИСИ — СВОИМ `<span>`,
 * А НЕ ГОЛЫМ ТЕКСТОМ. Переводчик Google подменяет текстовые узлы своими
 * `<font>`, а React держит ссылки на прежние: голый текст рядом
 * с элементом — это отдельный текстовый узел, и при следующей правке
 * React пишет в снятый узел (на экране остаётся старое) или роняет
 * страницу на `removeChild`. У элемента с одной строкой внутри React
 * меняет `textContent` целиком, и подмена ему не мешает. А один
 * внешний элемент держит фразу одним куском и в сетке: у `.ad label`
 * куски иначе разъехались бы по строкам сетки.
 */
function kuskami(kuski: string[], dannoe: (k: string) => ReactNode): ReactNode {
  return (
    <span>
      {kuski.map((k, i) => (i % 2 === 1 ? <Bukvalno key={i}>{dannoe(k)}</Bukvalno> : k ? <span key={i}>{k}</span> : null))}
    </span>
  );
}

/**
 * Почты и ники внутри нашего же текста — документов, таблички, подсказки.
 *
 * Текст переводить можно, а адрес в нём нет: переведённый адрес ведёт
 * не туда. Адреса находятся по виду (`x@y.z` и `@ник`) и встают своими
 * узлами под защитой; текст без адресов остаётся строкой.
 */
const ADRES = /([\w.+-]+@[\w-]+(?:\.[\w-]+)+|@\w+)/;
export function sAdresami(tekst: string): ReactNode {
  const kuski = tekst.split(ADRES);
  return kuski.length === 1 ? tekst : kuskami(kuski, (k) => k);
}

/**
 * Фраза с данными внутри: «взял {kto}», «Код отправлен на {email}».
 *
 * ⚠️ ПОДСТАНОВКА СКЛЕИВАЕТ ДАННЫЕ С НАДПИСЬЮ В ОДНУ СТРОКУ, а строку
 * переводчик переводит целиком — и почту внутри вместе с ней. Поэтому
 * фраза собирается с МЕТКАМИ на месте данных, режется по ним, и данные
 * встают обратно своими узлами под `translate="no"`; слова вокруг
 * переводятся как раньше. Собирает фразу вызывающий — словарём админки
 * или шаблонной строкой, — поэтому второй копии надписей здесь нет.
 */
export function frazaSDannymi(
  sobrat: (metki: Record<string, string>) => string,
  dannye: Record<string, string>,
): ReactNode {
  const metki = Object.fromEntries(Object.keys(dannye).map((imya) => [imya, `\u0001${imya}\u0001`]));
  return kuskami(sobrat(metki).split('\u0001'), (imya) => dannye[imya]);
}
