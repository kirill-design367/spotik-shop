/**
 * Шапка блока: заголовок и подводка. Больше ничего.
 *
 * ⚠️ НАДЗАГОЛОВКА БОЛЬШЕ НЕТ. До девятнадцатой итерации над каждым блоком
 * стояла тонкая линия с номером трека, словом-надзаголовком и короткой
 * цифровой сводкой справа. Арт-директор снял всё это целиком: блок
 * понятен по своему заголовку, а нумеровать его не нужно. Вместе
 * с номером ушли и линия, и сводка — от полосы не осталось ничего,
 * что стоило бы держать.
 *
 * ТИХИЙ ВАРИАНТ (quiet) остаётся: в блоке тарифов самый крупный набор —
 * это тело блока, и второй крупный набор в той же секции дерётся
 * с первым.
 */
export default function SectionHead({
  title,
  lead,
  quiet = false,
  center = false,
}: {
  title: string;
  lead?: string;
  /** Заголовок в размер подзаголовка: вес блока держит его тело. */
  quiet?: boolean;
  /** Выключка по центру — для блоков, у которых тело центровано. */
  center?: boolean;
}) {
  return (
    <header className={`shead${quiet ? ' shead--quiet' : ''}${center ? ' shead--center' : ''}`}>
      <h2 className={quiet ? 'shead__title' : 'h-section shead__title'}>{title}</h2>
      {lead ? <p className="lead shead__lead">{lead}</p> : null}
    </header>
  );
}
