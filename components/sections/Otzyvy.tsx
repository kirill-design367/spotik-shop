import SectionHead from './SectionHead';
import OtzyvyPleer, { type TrekOtzyva } from './OtzyvyPleer';

/**
 * БЛОК «ОТЗЫВЫ» — ОТЗЫВЫ КАК ПЛЕЙЛИСТ (пятьдесят четвёртая итерация).
 *
 * Постановка: «Каждый отзыв — трек в очереди: имя — исполнитель, первые
 * слова отзыва — название, дата справа, где у трека длительность.
 * Текущий отзыв раскрыт крупно, как экран „Сейчас играет"».
 *
 * ⚠️ ТОЛЬКО НАСТОЯЩИЕ ОТЗЫВЫ И НИ ОДНОЙ ЗАГЛУШКИ: блок рисует ровно то,
 * что пришло пропом из базы, а пока опубликовано меньше трёх, его
 * не рисует `app/page.tsx` вовсе — ни разметки, ни заголовка.
 *
 * ⚠️ КОМПОНЕНТ СЕРВЕРНЫЙ, А ПЛЕЕР — КЛИЕНТСКИЙ ЛИСТ (Р-15). Здесь живёт
 * то, что от скрипта не зависит: секция, заголовок и строчка, которая
 * включает раскладку плеера.
 *
 * ── РАСКЛАДКУ «ОДНА ЯЧЕЙКА» ВКЛЮЧАЕТ АТРИБУТ, И СТАВИТ ЕГО СКРИПТ ──────
 * Без скрипта отзывы стоят обычным списком и видны все (поправка после
 * рецензии, то же правило, что у появления строк и у вопросов: Р-36,
 * Р-58) — прятать безусловно нельзя ничего. Атрибут `data-pl` ставит
 * эффект плеера, но ещё раньше — эта строчка СРАЗУ ПОСЛЕ разметки
 * блока, в разборе HTML, до первой отрисовки. Поставь его только эффект —
 * список из двенадцати отзывов успевал бы показаться и схлопнуться
 * в плеер при гидратации, и страница под ним прыгала бы вверх у того,
 * кто перезагрузил её на вопросах: позицию прокрутки скрипт
 * восстанавливает ещё до гидратации (Р-37).
 */
export default function Otzyvy({ treki }: { treki: TrekOtzyva[] }) {
  return (
    <section id="otzyvy" className="section section--clipx otzyvy" aria-labelledby="otzyvy-h">
      <div className="shell">
        <SectionHead title="Отзывы" id="otzyvy-h" />
        <OtzyvyPleer treki={treki} />
        <script
          dangerouslySetInnerHTML={{
            __html: "try{var e=document.getElementById('pl-koren');if(e)e.setAttribute('data-pl','')}catch(e){}",
          }}
        />
      </div>
    </section>
  );
}
