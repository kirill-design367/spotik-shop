'use client';

import { useEffect, useId, useRef } from 'react';
import SectionHead from './SectionHead';
import { onLayoutChange, onScrollY, scroller } from '@/lib/scroll';
import { prefersReducedMotion } from '@/lib/motion';

/**
 * БЛОК ВОПРОСОВ — ОТВЕТ ВСТАЁТ НА МЕСТО ВОПРОСА.
 *
 * Вопросы стоят колонкой по центру крупным кеглем, все сразу. По мере
 * прокрутки вопрос гаснет, и на его месте проявляется ответ. Прокрутил
 * назад — ответ ушёл, вопрос вернулся. Ничего не по клику.
 *
 * ── ДВЕ ФАЗЫ ПОДРЯД, А НЕ ПЕРЕКРЁСТНОЕ ЗАТУХАНИЕ ──────────────────────────
 * ⚠️ ДВАДЦАТАЯ ИТЕРАЦИЯ ОТМЕНИЛА ПЕРЕКРЁСТНЫЙ ПЕРЕХОД. При нём на
 * медленной прокрутке вопрос и ответ видны ОДНОВРЕМЕННО, каждый вполсилы,
 * и налезают друг на друга — премиальность на этом и ломалась. Теперь
 * фазы идут строго по очереди:
 *
 *     вопрос разгорается  →  стоит  →  гаснет ДО НУЛЯ
 *     · · · пустая пауза · · ·
 *     ответ проявляется
 *
 * Между фазами есть зазор, в котором не видно ни того, ни другого:
 * короткая пустота лучше наложения, и это прямая постановка.
 *
 * Считаются обе прозрачности В JS и уезжают двумя переменными: кусочная
 * функция из трёх участков в `calc` читалась бы как шифр, а стоит она
 * ровно столько же — две записи вместо одной.
 *
 * ── ПОЧЕМУ ОДНА ЯЧЕЙКА СЕТКИ, А НЕ ДВА АБСОЛЮТА ───────────────────────────
 * Высота контейнера обязана быть по БОЛЬШЕМУ из двух, иначе раскладка
 * прыгает на смене активного. Абсолютом это пришлось бы мерить
 * и записывать; сетка делает то же даром: `grid-area: 1 / 1` у обоих.
 *
 * ── БЕЗ СКРИПТА И ПРИ «УМЕНЬШИТЬ ДВИЖЕНИЕ» ────────────────────────────────
 * Подмена включается атрибутом `data-swap`, и ставит его скрипт — только
 * когда подписался. Нет скрипта, «уменьшить движение» — ячейка
 * разворачивается в две строки, и видно И вопрос, И ответ.
 *
 * Тексты ответов — ЗАГЛУШКИ. Финальные формулировки даёт арт-директор:
 * они затрагивают обязательства перед клиентом.
 */
const QA = [
  {
    q: 'Нужен ли VPN?',
    a: 'Здесь будет ответ про то, что VPN не требуется ни для оплаты, ни для прослушивания, и что настройки сети менять не нужно.',
  },
  {
    q: 'Как оплатить из России?',
    a: 'Здесь будет ответ про оплату российской картой и через СБП, без зарубежных карт и посредников.',
  },
  {
    q: 'Что если аккаунт перестанет работать?',
    a: 'Здесь будет ответ про то, что делает сервис, если доступ прервался раньше срока, и в какой срок вопрос решается.',
  },
  {
    q: 'Можно ли слушать с нескольких устройств?',
    a: 'Здесь будет ответ про число одновременных устройств и про то, чем тарифы на двоих и на троих отличаются от индивидуального.',
  },
  {
    q: 'Сколько ждать после оплаты?',
    a: 'Здесь будет ответ про фактическое время от оплаты до выдачи доступа и про то, что происходит, если оно вышло за обычные рамки.',
  },
  {
    q: 'Что если я передумаю?',
    a: 'Здесь будет ответ про возврат: в какой срок, на каких условиях и каким способом приходят деньги.',
  },
];

/**
 * Линия отсчёта в экране, ширина зоны затухания и ПОЛКА.
 *
 * Полка задаёт, какую долю зоны занимает переход, а остальное — стояние
 * на полной яркости. И то, и другое стоит денег в пикселях прокрутки,
 * потому что вся зона у вопроса невелика: шаг между вопросами на 390
 * около 150 px, и весь цикл «разгорелся — погас — пауза — ответ»
 * укладывается в него.
 *
 * ⚠️ ПОЛКУ 0.92 ПРИШЛОСЬ ОТКАТИТЬ. Она делала переход длинным, но
 * съедала стояние: ответ был на полной яркости в пределах ±7 px
 * прокрутки, то есть мелькал. Поймал это не глаз, а сплошной перебор:
 * «ответ не доходит до полной яркости» на шаге 8 px — сторож попадал
 * мимо семипиксельного окна. Взято 0.55: стояние ±34 px, переход 42 px,
 * то есть примерно как в прошлой итерации, на которую жалоб не было.
 * См. Р-61 и открытый вопрос 37.
 */
const REF = 0.46;
const BAND = 0.62;
const PLATEAU = 0.55;

/**
 * ГРАНИЦЫ ФАЗ по весу 0…1. Между `Q_OUT` и `A_IN` лежит пустая пауза:
 * вопроса уже нет, ответа ещё нет. Она короткая и намеренная.
 */
const DIM = 0.8; // дальний вопрос: приглушён еле-еле, читается свободно
const Q_UP = 0.18; // к этому весу вопрос разгорается до полной яркости
const Q_HOLD = 0.62; // до этого веса СТОИТ БЕЛЫМ, и это самая длинная фаза
const Q_OUT = 0.78; // здесь гаснет до нуля
const A_IN = 0.84; // здесь ответ только начинает проявляться
const A_FULL = 0.97; // здесь он в полную силу

/*
 * ⚠️ ФАЗУ «СТОИТ БЕЛЫМ» ПРИШЛОСЬ РАСТЯНУТЬ ДВАЖДЫ, и оба раза это нашёл
 * сплошной перебор, а не глаз. Сначала полной яркости не достигал ОТВЕТ
 * (окно ±7 px прокрутки), потом — ВОПРОС (окно 15 px на 2560). Обе
 * величины стали шире в разы: белым вопрос стоит почти четверть зоны,
 * ответ — почти половину. Это ровно тот случай, ради которого сторож
 * и обязан падать, когда что-то «не рисуется»: наложения он не находил
 * ни разу, и без второй проверки приём молча работал бы наполовину.
 */

function clamp01(v: number) {
  return v < 0 ? 0 : v > 1 ? 1 : v;
}

export default function Faq() {
  const listRef = useRef<HTMLDivElement>(null);
  const base = useId();

  useEffect(() => {
    const list = listRef.current;
    const sc = scroller();
    if (!list || !sc || prefersReducedMotion()) return;

    let items: HTMLElement[] = [];
    let mids: number[] = [];
    let band = 1;

    const measure = () => {
      const shift = sc.getBoundingClientRect().top - sc.scrollTop;
      items = Array.from(list.querySelectorAll<HTMLElement>('.qa__item'));
      mids = items.map((el) => {
        const r = el.getBoundingClientRect();
        return r.top - shift + r.height / 2;
      });
      const step =
        mids.length > 1 ? (mids[mids.length - 1] - mids[0]) / (mids.length - 1) : sc.clientHeight;
      band = Math.max(1, step * BAND);
    };

    const read = (y: number) => {
      const line = y + sc.clientHeight * REF;
      for (let i = 0; i < items.length; i += 1) {
        const raw = 1 - Math.abs(mids[i] - line) / band;
        const w = raw <= 0 ? 0 : raw >= PLATEAU ? 1 : raw / PLATEAU;

        /* ФАЗА ОДИН — вопрос. Разгорается из приглушённого в белый,
           стоит, потом гаснет ДО НУЛЯ. */
        const oq =
          w <= Q_UP
            ? DIM + (1 - DIM) * (w / Q_UP)
            : w <= Q_HOLD
              ? 1
              : 1 - clamp01((w - Q_HOLD) / (Q_OUT - Q_HOLD));

        /* ФАЗА ДВА — ответ. Начинается ПОЗЖЕ, чем кончилась первая. */
        const oa = clamp01((w - A_IN) / (A_FULL - A_IN));

        items[i].style.setProperty('--oq', oq.toFixed(3));
        items[i].style.setProperty('--oa', oa.toFixed(3));
      }
    };

    /* ⚠️ АТРИБУТ СТАВИТСЯ ДО ИЗМЕРЕНИЯ, И ЭТО НЕ ПЕРЕСТАНОВКА РАДИ
       КРАСОТЫ. Без `data-swap` вопрос и ответ стоят ДРУГ ПОД ДРУГОМ,
       и шаг между вопросами получается вдвое больше настоящего;
       померив до атрибута, мы клали в `band` чужое число и попадали
       мимо. Обычно это чинилось следующим же пересчётом раскладки,
       но не всегда — и сплошной перебор поймал это как «ответ
       не доходит до полной яркости» (0.49 на 390, 0.90 на 2560).
       Ставим атрибут, потом читаем геометрию: это один синхронный
       рефлоу при монтировании и ни одного в кадре. */
    list.setAttribute('data-swap', '');
    measure();
    const offLayout = onLayoutChange(measure);
    const offScroll = onScrollY(read);
    return () => {
      offLayout();
      offScroll();
      list.removeAttribute('data-swap');
      for (const el of items) {
        el.style.removeProperty('--oq');
        el.style.removeProperty('--oa');
      }
    };
  }, []);

  return (
    <section id="faq" className="section">
      <div className="shell">
        <SectionHead title="Ваши вопросы" center />

        <div ref={listRef} className="qa">
          {QA.map((item, i) => {
            const aid = `${base}-a-${i}`;
            return (
              <div key={item.q} className="qa__item">
                {/* Вопрос и ответ — в ОДНОЙ ячейке: высота берётся
                    по большему из двух, и раскладка не прыгает. */}
                <div className="qa__swap">
                  <h3 className="qa__q">{item.q}</h3>
                  {/* Ответ лежит в разметке ВСЕГДА — и для индексации,
                      и для скринридера: прокрутка меняет только его вид. */}
                  <p id={aid} className="qa__a">
                    {item.a}
                  </p>
                </div>
              </div>
            );
          })}
        </div>
      </div>
    </section>
  );
}
