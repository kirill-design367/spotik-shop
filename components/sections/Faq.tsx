'use client';

import { useEffect, useId, useRef } from 'react';
import SectionHead from './SectionHead';
import { onLayoutChange, onScrollY, scroller } from '@/lib/scroll';
import { prefersReducedMotion } from '@/lib/motion';

/**
 * БЛОК ВОПРОСОВ — ОТВЕТ ВСТАЁТ НА МЕСТО ВОПРОСА.
 *
 * Вопросы стоят колонкой по центру крупным кеглем, все сразу. По мере
 * прокрутки вопрос гаснет, и на его месте проявляется ответ. Прокрутил
 * назад — ответ ушёл, вопрос вернулся. Ничего не по клику.
 *
 * ── ШТОРКА: ГРАНИЦА ОБРЕЗКИ ЕДЕТ ПО ЯЧЕЙКЕ ────────────────────────────────
 * ⚠️ ДВАДЦАТЬ ВТОРАЯ ИТЕРАЦИЯ ОТМЕНИЛА МГНОВЕННУЮ ПОДМЕНУ. Она была
 * честным выводом из «ни наложения, ни пустоты» — но вывод верен
 * только для затухания ПРОЗРАЧНОСТЬЮ. У обрезки третье состояние есть:
 *
 *     вопрос и ответ лежат в одной ячейке друг над другом, и между
 *     ними идёт ГРАНИЦА. Выше неё виден ответ, ниже — вопрос.
 *     Граница едет по ячейке при прокрутке.
 *
 * Каждый пиксель в каждый момент показывает ровно одну из половин:
 * наложения нет ПО ПОСТРОЕНИЮ (области дополняют друг друга и делят
 * общую кромку), пустоты нет ПО ПОСТРОЕНИЮ (их объединение — вся
 * ячейка), а движение непрерывное. Прозрачность в переходе
 * не участвует вовсе.
 *
 * Граница ДИАГОНАЛЬНАЯ: наклон 14 % высоты ячейки. Прямая
 * горизонтальная читается как жалюзи, диагональ — как смахивание.
 * Обе половины получают `clip-path: polygon(...)` с ОДНИМИ И ТЕМИ ЖЕ
 * двумя ординатами, поэтому разъехаться им нечем.
 *
 * ── ОТВЕТ НА ЭКРАНЕ ВСЕГДА ОДИН, И ЭТО ГЕОМЕТРИЯ, А НЕ НАДЗОР ────────────
 * Прошлая итерация расширила зону веса с 0.62 до 0.92 шага — и ровно
 * этим сломала главное: при широкой зоне два СОСЕДНИХ вопроса разом
 * оказывались активными, и на экране висели два ответа. Сторож этого
 * не видел, потому что проверял каждый вопрос поодиночке.
 *
 * Теперь зона считается не долей, а ПИКСЕЛЯМИ, и связана неравенством:
 *
 *     HOLD + WIPE ≤ 0.47 × шаг между вопросами
 *
 * Расстояния до двух соседей в сумме равны шагу, значит внутри
 * 0.47 шага может оказаться только один — двум ответам взяться неоткуда.
 * Сторож проверяет это отдельной строкой, перебором по всей прокрутке.
 *
 * ── ПОЧЕМУ ОДНА ЯЧЕЙКА СЕТКИ, А НЕ ДВА АБСОЛЮТА ───────────────────────────
 * Высота контейнера обязана быть по БОЛЬШЕМУ из двух, иначе раскладка
 * прыгает на смене активного. Абсолютом это пришлось бы мерить
 * и записывать; сетка делает то же даром: `grid-area: 1 / 1` у обоих.
 *
 * ── БЕЗ СКРИПТА И ПРИ «УМЕНЬШИТЬ ДВИЖЕНИЕ» ────────────────────────────────
 * Подмена включается атрибутом `data-swap`, и ставит его скрипт — только
 * когда подписался. Нет скрипта, «уменьшить движение» — ячейка
 * разворачивается в две строки, и видно И вопрос, И ответ.
 *
 * Тексты ответов — ЗАГЛУШКИ. Финальные формулировки даёт арт-директор:
 * они затрагивают обязательства перед клиентом.
 */
const QA = [
  {
    q: 'Нужен ли VPN?',
    a: 'Здесь будет ответ про то, что VPN не требуется ни для оплаты, ни для прослушивания, и что настройки сети менять не нужно.',
  },
  {
    q: 'Как оплатить из России?',
    a: 'Здесь будет ответ про оплату российской картой и через СБП, без зарубежных карт и посредников.',
  },
  {
    q: 'Что если аккаунт перестанет работать?',
    a: 'Здесь будет ответ про то, что делает сервис, если доступ прервался раньше срока, и в какой срок вопрос решается.',
  },
  {
    q: 'Можно ли слушать с нескольких устройств?',
    a: 'Здесь будет ответ про число одновременных устройств и про то, чем тарифы на двоих и на троих отличаются от индивидуального.',
  },
  {
    q: 'Сколько ждать после оплаты?',
    a: 'Здесь будет ответ про фактическое время от оплаты до выдачи доступа и про то, что происходит, если оно вышло за обычные рамки.',
  },
  {
    q: 'Что если я передумаю?',
    a: 'Здесь будет ответ про возврат: в какой срок, на каких условиях и каким способом приходят деньги.',
  },
];

/**
 * ЛИНИЯ ОТСЧЁТА И ТРИ РАССТОЯНИЯ, ВСЕ В ПИКСЕЛЯХ ПРОКРУТКИ.
 *
 * Доли шага здесь больше не годятся: именно доля (0.92 вместо 0.62)
 * и дала два ответа на экране разом. Считаем от шага между вопросами
 * и жёстко ограничиваем сумму.
 *
 *     HOLD — ответ виден ЦЕЛИКОМ, шторка открыта до упора;
 *     WIPE — ход самой шторки, от закрытой до открытой;
 *     FADE — до этого вопрос разгорается из приглушённого в белый,
 *            чтобы шторка пошла уже по яркому.
 *
 * Ход шторки подобран по ощущению: 0.25…0.35 с при обычной скорости
 * колеса (около 260 px/с) — это 70…90 пикселей прокрутки.
 */
const REF = 0.46;
/**
 * Ход шторки в пикселях прокрутки; от шага, но с потолком и полом.
 *
 * ⚠️ ЗАМЕРЕННЫЙ ХОД КОРОЧЕ НОМИНАЛЬНОГО, И ЭТО СМЯГЧЕНИЕ, А НЕ ОШИБКА.
 * Граница идёт по smoothstep, у которого оба конца плоские: пока
 * шторка видимо трогается с места, номинального хода уходит около
 * трети. Сторож меряет ВИДИМОЕ движение (доля от 0.02 до 0.98),
 * и его число — примерно 0.66 от `WIPE_*`.
 */
const WIPE_MIN = 72;
const WIPE_MAX = 128;
const WIPE_OF_STEP = 0.32;
/** Разгорание вопроса перед шторкой. */
const FADE = 64;
/** Дальний вопрос приглушён еле-еле: читается свободно. */
const DIM = 0.72;
/**
 * ⚠️ ПОТОЛОК НА СУММУ HOLD + WIPE. Два соседних вопроса делят между
 * собой шаг: расстояния до линии в сумме равны ему. Значит попасть
 * внутрь 0.47 шага может только один из двух — при любом положении
 * прокрутки. Это и есть гарантия «ответ на экране один», и держится
 * она арифметикой, а не присмотром.
 */
const REACH_OF_STEP = 0.47;
/** Наклон границы, доля высоты ячейки. */
const SLANT = 14;

/** Плавный старт и плавная остановка шторки. */
function smooth(t: number) {
  return t * t * (3 - 2 * t);
}

function clamp01(v: number) {
  return v < 0 ? 0 : v > 1 ? 1 : v;
}

export default function Faq() {
  const listRef = useRef<HTMLDivElement>(null);
  const base = useId();

  useEffect(() => {
    const list = listRef.current;
    const sc = scroller();
    if (!list || !sc || prefersReducedMotion()) return;

    let items: HTMLElement[] = [];
    let mids: number[] = [];
    /* Оба расстояния — в пикселях прокрутки, считаются от шага. */
    let hold = 1;
    let wipe = 1;

    const measure = () => {
      const shift = sc.getBoundingClientRect().top - sc.scrollTop;
      items = Array.from(list.querySelectorAll<HTMLElement>('.qa__item'));
      mids = items.map((el) => {
        const r = el.getBoundingClientRect();
        return r.top - shift + r.height / 2;
      });
      const step =
        mids.length > 1 ? (mids[mids.length - 1] - mids[0]) / (mids.length - 1) : sc.clientHeight;
      wipe = Math.max(WIPE_MIN, Math.min(WIPE_MAX, step * WIPE_OF_STEP));
      /* Ответ виден ровно там, куда не дотягивается сосед. Если
         на узком экране места не хватает даже на это — режем СТОЯНИЕ,
         а не шторку: короткое стояние читается, оборванная шторка нет. */
      hold = Math.max(16, step * REACH_OF_STEP - wipe);
    };

    /* Кэш последнего записанного состояния: далёкие вопросы стоят
       неизменными, и переписывать им переменные каждый кадр — это
       пересчёт стилей на ровном месте. */
    const last: string[] = [];

    const read = (y: number) => {
      const line = y + sc.clientHeight * REF;
      for (let i = 0; i < items.length; i += 1) {
        const a = Math.abs(mids[i] - line);

        /* ШТОРКА. 1 — открыта целиком (виден ответ), 0 — закрыта
           (виден вопрос). Между ними едет граница, и обе половины
           берут её из ОДНОЙ величины. */
        const cut = smooth(clamp01((hold + wipe - a) / wipe));

        /* Вопрос разгорается ДО того, как пойдёт шторка: она обязана
           идти уже по яркому набору, иначе переход читается как
           затухание, а не как смахивание. */
        const oq = DIM + (1 - DIM) * clamp01((hold + wipe + FADE - a) / FADE);

        /* Диагональ. При cut = 0 верхняя область вырождается в точку
           у правого верхнего угла, при cut = 1 нижняя — у левого
           нижнего: обе половины уходят целиком, ни одна не обрезана
           наполовину в покое. */
        const c1 = cut * (100 + SLANT) - SLANT;
        const c2 = c1 + SLANT;

        const st = items[i].style;
        const key = `${oq.toFixed(3)} ${c1.toFixed(2)}`;
        if (last[i] === key) continue;
        last[i] = key;
        st.setProperty('--oq', oq.toFixed(3));
        st.setProperty('--c1', `${c1.toFixed(2)}%`);
        st.setProperty('--c2', `${c2.toFixed(2)}%`);
      }
    };

    /* ⚠️ АТРИБУТ СТАВИТСЯ ДО ИЗМЕРЕНИЯ, И ЭТО НЕ ПЕРЕСТАНОВКА РАДИ
       КРАСОТЫ. Без `data-swap` вопрос и ответ стоят ДРУГ ПОД ДРУГОМ,
       и шаг между вопросами получается вдвое больше настоящего;
       померив до атрибута, мы клали в `band` чужое число и попадали
       мимо. Обычно это чинилось следующим же пересчётом раскладки,
       но не всегда — и сплошной перебор поймал это как «ответ
       не доходит до полной яркости» (0.49 на 390, 0.90 на 2560).
       Ставим атрибут, потом читаем геометрию: это один синхронный
       рефлоу при монтировании и ни одного в кадре. */
    list.setAttribute('data-swap', '');
    measure();
    const offLayout = onLayoutChange(measure);
    const offScroll = onScrollY(read);
    return () => {
      offLayout();
      offScroll();
      list.removeAttribute('data-swap');
      for (const el of items) {
        for (const prop of ['--oq', '--c1', '--c2']) el.style.removeProperty(prop);
      }
    };
  }, []);

  return (
    <section id="faq" className="section">
      <div className="shell">
        <SectionHead title="Ваши вопросы" center />

        <div ref={listRef} className="qa">
          {QA.map((item, i) => {
            const aid = `${base}-a-${i}`;
            return (
              <div key={item.q} className="qa__item">
                {/* Вопрос и ответ — в ОДНОЙ ячейке: высота берётся
                    по большему из двух, и раскладка не прыгает. */}
                <div className="qa__swap">
                  {/* ⚠️ ОБРЕЗАЮТСЯ ОБЁРТКИ, А НЕ САМИ ТЕКСТЫ. Проценты
                      в `clip-path` считаются от СОБСТВЕННОГО бокса, а вопрос
                      и ответ разной высоты: одна и та же ордината попадала
                      у них в разные пиксели, и границы расходились до 27 px.
                      Обёртки растянуты на всю ячейку и потому равны друг
                      другу ровно. */}
                  <div className="qa__half qa__half--q">
                    <h3 className="qa__q">{item.q}</h3>
                  </div>
                  {/* Ответ лежит в разметке ВСЕГДА — и для индексации,
                      и для скринридера: прокрутка меняет только его вид. */}
                  <div className="qa__half qa__half--a">
                    <p id={aid} className="qa__a">
                      {item.a}
                    </p>
                  </div>
                </div>
              </div>
            );
          })}
        </div>
      </div>
    </section>
  );
}
