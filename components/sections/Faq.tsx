'use client';

import { useEffect, useId, useRef } from 'react';
import SectionHead from './SectionHead';
import { onLayoutChange, onScrollY, scroller } from '@/lib/scroll';
import { prefersReducedMotion } from '@/lib/motion';

/**
 * БЛОК ВОПРОСОВ — ОТВЕТ ВСТАЁТ НА МЕСТО ВОПРОСА В ОДИН КАДР.
 *
 * Вопросы стоят колонкой по центру крупным кеглем, все сразу. При
 * пересечении линии отсчёта вопрос СМЕНЯЕТСЯ ответом — мгновенно,
 * без затухания и без движения. Прокрутил назад — так же мгновенно
 * вернулся вопрос. Ничего не по клику.
 *
 * ── ДВАДЦАТЬ ТРЕТЬЯ ИТЕРАЦИЯ: ШТОРКА СНЯТА ───────────────────────────────
 * ⚠️ Двадцать вторая итерация делила вопрос и ответ ДИАГОНАЛЬНОЙ
 * ГРАНИЦЕЙ ОБРЕЗКИ, которая ехала по ячейке при прокрутке (Р-67).
 * Приём работал и был честным, но арт-директор снял его одной
 * строкой: «читается старомодно». Вместо него — жёсткая смена
 * содержимого, как в блоке наград на эталоне: в этой точке просто
 * оказывается другое.
 *
 * Отсюда упрощается ВСЁ. Ни наложения, ни пустого кадра нет
 * по построению не потому, что области дополняют друг друга, а
 * потому, что состояний ровно два и они взаимоисключающие:
 *
 *     --on = 1  — виден ответ,  вопрос скрыт;
 *     --on = 0  — виден вопрос, ответ скрыт.
 *
 * Переход не занимает ни одного промежуточного кадра: величина
 * дискретна, переходов CSS на ней нет.
 *
 * ── ОТВЕТ НА ЭКРАНЕ ОДИН, И ТЕПЕРЬ ЭТО НЕ НЕРАВЕНСТВО, А ВЫБОР ───────────
 * Прошлая итерация держала «один ответ» неравенством
 * `HOLD + WIPE ≤ 0.47 × шаг`: зона активности была уже половины
 * шага, поэтому внутрь неё мог попасть только один вопрос. Теперь
 * гарантия сильнее и проще: активным объявляется БЛИЖАЙШИЙ к линии
 * вопрос, а ближайший по определению один. Двум ответам взяться
 * неоткуда ни при каком расстоянии между вопросами.
 *
 * Дальше линии `REACH × шаг` не активен никто: выше и ниже блока
 * все вопросы стоят вопросами.
 *
 * ── ВОЗДУХ МЕЖДУ ВОПРОСАМИ ВЕРНУЛСЯ К ПРЕЖНЕМУ ──────────────────────────
 * Ход шторки считался от шага между вопросами, и ради него промежуток
 * был поднят до `clamp(190px, 14vw, 260px)`. Хода больше нет —
 * растягивать блок незачем, промежуток вернулся к
 * `clamp(96px, 10vw, 180px)`.
 *
 * ── ПОЧЕМУ ОДНА ЯЧЕЙКА СЕТКИ, А НЕ ДВА АБСОЛЮТА ───────────────────────────
 * Высота контейнера обязана быть по БОЛЬШЕМУ из двух, иначе раскладка
 * прыгает на смене активного. Абсолютом это пришлось бы мерить
 * и записывать; сетка делает то же даром: `grid-area: 1 / 1` у обоих.
 *
 * ── БЕЗ СКРИПТА И ПРИ «УМЕНЬШИТЬ ДВИЖЕНИЕ» ────────────────────────────────
 * Подмена включается атрибутом `data-swap`, и ставит его скрипт — только
 * когда подписался. Нет скрипта, «уменьшить движение» — ячейка
 * разворачивается в две строки, и видно И вопрос, И ответ.
 *
 * Тексты ответов — ЗАГЛУШКИ. Финальные формулировки даёт арт-директор:
 * они затрагивают обязательства перед клиентом.
 */
const QA = [
  {
    q: 'Нужен ли VPN?',
    a: 'Здесь будет ответ про то, что VPN не требуется ни для оплаты, ни для прослушивания, и что настройки сети менять не нужно.',
  },
  {
    q: 'Как оплатить из России?',
    a: 'Здесь будет ответ про оплату российской картой и через СБП, без зарубежных карт и посредников.',
  },
  {
    q: 'Что если аккаунт перестанет работать?',
    a: 'Здесь будет ответ про то, что делает сервис, если доступ прервался раньше срока, и в какой срок вопрос решается.',
  },
  {
    q: 'Можно ли слушать с нескольких устройств?',
    a: 'Здесь будет ответ про число одновременных устройств и про то, чем тарифы на двоих и на троих отличаются от индивидуального.',
  },
  {
    q: 'Сколько ждать после оплаты?',
    a: 'Здесь будет ответ про фактическое время от оплаты до выдачи доступа и про то, что происходит, если оно вышло за обычные рамки.',
  },
  {
    q: 'Что если я передумаю?',
    a: 'Здесь будет ответ про возврат: в какой срок, на каких условиях и каким способом приходят деньги.',
  },
];

/**
 * ЛИНИЯ ОТСЧЁТА И ЕДИНСТВЕННОЕ РАССТОЯНИЕ.
 *
 * Трёх расстояний (стояние, ход шторки, разгорание) больше нет:
 * переключение дискретно, длительности у него нет вовсе. Осталась
 * линия отсчёта и радиус, дальше которого не активен никто.
 */
const REF = 0.46;
/**
 * Радиус активности в долях шага между вопросами.
 *
 * ⚠️ ОН БОЛЬШЕ ПОЛОВИНЫ ШАГА, И ЭТО БЕЗОПАСНО. Двух ответов разом
 * он дать не может: активным становится не «всякий, кто ближе
 * радиуса», а БЛИЖАЙШИЙ из них, а ближайший ровно один. Радиус
 * решает только одно — где блок начинается и где кончается.
 */
const REACH_OF_STEP = 0.55;
/** Неактивный вопрос приглушён: он читается, но не спорит с ответом. */
const DIM = 0.62;

export default function Faq() {
  const listRef = useRef<HTMLDivElement>(null);
  const base = useId();

  useEffect(() => {
    const list = listRef.current;
    const sc = scroller();
    if (!list || !sc || prefersReducedMotion()) return;

    let items: HTMLElement[] = [];
    let mids: number[] = [];
    let reach = 1;

    const measure = () => {
      const shift = sc.getBoundingClientRect().top - sc.scrollTop;
      items = Array.from(list.querySelectorAll<HTMLElement>('.qa__item'));
      mids = items.map((el) => {
        const r = el.getBoundingClientRect();
        return r.top - shift + r.height / 2;
      });
      const step =
        mids.length > 1 ? (mids[mids.length - 1] - mids[0]) / (mids.length - 1) : sc.clientHeight;
      reach = step * REACH_OF_STEP;
    };

    /* Кэш последнего состояния: переключение затрагивает ровно два
       вопроса из шести, остальным переписывать переменную незачем. */
    const last: number[] = [];

    const read = (y: number) => {
      const line = y + sc.clientHeight * REF;
      /* АКТИВЕН БЛИЖАЙШИЙ, и это вся гарантия «ответ на экране один»:
         ближайший по определению один, сколько бы вопросов ни стояло
         рядом и как бы тесно они ни стояли. */
      let best = -1;
      let bd = Infinity;
      for (let i = 0; i < mids.length; i += 1) {
        const a2 = Math.abs(mids[i] - line);
        if (a2 < bd) {
          bd = a2;
          best = i;
        }
      }
      if (bd > reach) best = -1;
      for (let i = 0; i < items.length; i += 1) {
        const on = i === best ? 1 : 0;
        if (last[i] === on) continue;
        last[i] = on;
        items[i].style.setProperty('--on', String(on));
      }
    };

    /* ⚠️ АТРИБУТ СТАВИТСЯ ДО ИЗМЕРЕНИЯ, И ЭТО НЕ ПЕРЕСТАНОВКА РАДИ
       КРАСОТЫ. Без `data-swap` вопрос и ответ стоят ДРУГ ПОД ДРУГОМ,
       и шаг между вопросами получается вдвое больше настоящего —
       а от шага считается радиус активности. Ставим атрибут, потом
       читаем геометрию: это один синхронный рефлоу при монтировании
       и ни одного в кадре. То же правило уже ловило нас трижды —
       гутер маршрута, `data-swap`, рельеф шагов. */
    list.setAttribute('data-swap', '');
    measure();
    const offLayout = onLayoutChange(measure);
    const offScroll = onScrollY(read);
    return () => {
      offLayout();
      offScroll();
      list.removeAttribute('data-swap');
      for (const el of items) el.style.removeProperty('--on');
    };
  }, []);

  return (
    <section id="faq" className="section">
      <div className="shell">
        <SectionHead title="Ваши вопросы" center />

        <div ref={listRef} className="qa">
          {QA.map((item, i) => {
            const aid = `${base}-a-${i}`;
            return (
              <div key={item.q} className="qa__item">
                {/* Вопрос и ответ — в ОДНОЙ ячейке: высота берётся
                    по большему из двух, и раскладка не прыгает. */}
                <div className="qa__swap">
                  {/* Половины лежат в одной ячейке друг поверх друга.
                      Видна ровно одна: `--on` дискретна, переходов
                      на ней нет, и промежуточного состояния не бывает. */}
                  <div className="qa__half qa__half--q">
                    <h3 className="qa__q">{item.q}</h3>
                  </div>
                  {/* Ответ лежит в разметке ВСЕГДА — и для индексации,
                      и для скринридера: прокрутка меняет только его вид. */}
                  <div className="qa__half qa__half--a">
                    <p id={aid} className="qa__a">
                      {item.a}
                    </p>
                  </div>
                </div>
              </div>
            );
          })}
        </div>
      </div>
    </section>
  );
}
