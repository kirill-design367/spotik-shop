'use client';

import { useEffect, useId, useRef } from 'react';
import SectionHead from './SectionHead';
import { finePointer, onLayoutChange, onScrollY, scroller } from '@/lib/scroll';
import { prefersReducedMotion } from '@/lib/motion';

/**
 * БЛОК ВОПРОСОВ — ОТВЕТ БЕЖИТ ОДНОЙ СТРОКОЙ ПОПЕРЁК ВОПРОСА.
 *
 * Вопросы стоят колонкой по центру крупным кеглем, все сразу и все
 * целиком. Ответ их не подменяет: он белой строкой идёт ПРЯМО ЧЕРЕЗ
 * набор вопроса, как строка деталей в блоке наград эталона.
 *
 * ── ДВАДЦАТЬ ЧЕТВЁРТАЯ ИТЕРАЦИЯ: ПОДМЕНА СНЯТА ЦЕЛИКОМ ───────────────────
 * Ось «как ответ встаёт на место вопроса» разворачивалась четырежды:
 * перекрёстное затухание (девятнадцатая) → две фазы с паузой
 * (двадцатая) → мгновенная подмена с движением вокруг неё
 * (двадцать первая) → диагональная шторка (двадцать вторая) →
 * жёсткая смена в один кадр (двадцать третья). Постановка
 * двадцать четвёртой снимает саму подмену: вопрос остаётся
 * на месте и виден всегда.
 *
 * ── ПОПЕРЁК ВОПРОСА, И ЧИТАЕМОСТЬ ДЕРЖИТ ПРИГЛУШЕНИЕ ────────────────────
 * Двадцать четвёртая итерация увела строку ПОД вопрос ровно потому,
 * что белая лента поверх белого набора в 68 px роняет читаемость
 * обоих. Двадцать пятая вернула её поперёк и назвала выход прямо:
 * пока строка бежит, САМ ВОПРОС ПРИГЛУШАЕТСЯ.
 *
 * ⚠️ ДВАДЦАТЬ ШЕСТАЯ ДОВЕЛА ОБЕ ВЕЛИЧИНЫ ДО КОНЦА: «строка крупнее
 * и светлее, вопрос за ней почти исчезает — сейчас он читается
 * серым, и две надписи спорят». Вопрос уходит на 0.12 вместо 0.36,
 * то есть 1.4:1 — силуэт угадывается, прочесть нельзя, спорить
 * нечем; строка выросла с 19…28 px до 23…35 и потяжелела
 * с веса 560 до 660. Приглушать сильнее нельзя: вопрос обязан
 * оставаться НА МЕСТЕ и быть виден (закон 26), иначе это снова
 * подмена.
 *
 * Полоса при этом лежит АБСОЛЮТОМ и места в потоке не занимает:
 * «раскладка не прыгает» выполняется по построению, резервировать
 * под неё высоту больше не нужно вовсе.
 *
 * ── ЧТО ЗАПУСКАЕТ СТРОКУ ────────────────────────────────────────────────
 * На точном указателе — НАВЕДЕНИЕ, и делает это ЧИСТЫЙ CSS: `:hover`
 * под медиазапросом. На касаниях наведения нет, и активным
 * объявляется вопрос, БЛИЖАЙШИЙ к линии отсчёта, — та же гарантия
 * «строка ровно одна», что и в прошлой итерации: ближайший
 * по определению один (Р-73). Признак — тип указателя, а не ширина
 * окна: то же правило, по которому решают Lenis и демпфер (Р-45).
 *
 * ── ПЕТЛЯ БЕЗ ШВА И БЕЗ ЕДИНОГО ЗАМЕРА В КАДРЕ ──────────────────────────
 * Дорожка несёт ЧЕТЫРЕ одинаковые копии ответа, ход круга — ровно
 * одна копия (−25 % ширины дорожки): в конце круга на месте каждого
 * знака стоит такой же знак из следующей копии, и стыка не видно
 * по построению (Р-56).
 *
 * ⚠️ КОПИЙ ИМЕННО ЧЕТЫРЕ, А НЕ ДВЕ, И ЭТО НАШЛА ПРОВЕРКА РАСТРОМ.
 * Ход равен одной копии, значит к концу круга полосу обязаны
 * закрывать ОСТАВШИЕСЯ: при двух копиях справа открывалась пустота
 * на полтысячи пикселей. Условие простое — (копий − 1) × ширина
 * копии ≥ ширина полосы.
 *
 * ⚠️ ДЛИТЕЛЬНОСТЬ У КАЖДОГО ОТВЕТА СВОЯ, И ЭТО ОБЯЗАТЕЛЬНО. Ответы
 * разной длины; при общей длительности короткий полз бы, а длинный
 * летел. Скорость задана числом (пикселей в секунду), а длительность
 * считается из ИЗМЕРЕННОЙ ширины копии — один раз при раскладке,
 * ни одного чтения в кадре.
 *
 * ── БЕЗ СКРИПТА И ПРИ «УМЕНЬШИТЬ ДВИЖЕНИЕ» ────────────────────────────────
 * Без скрипта на точном указателе всё работает как есть: наведение
 * ведёт CSS. При «уменьшить движение» строка не бежит вовсе и стоит
 * открытой — ответ виден неподвижно.
 *
 * ⚠️ ТЕКСТЫ ОТВЕТОВ ФИНАЛЬНЫЕ И ПРИШЛИ ОТ АРТ-ДИРЕКТОРА ДОСЛОВНО
 * (тридцать четвёртая итерация). Они затрагивают обязательства перед
 * клиентом — часы работы, срок выдачи, права владельца тарифа, —
 * поэтому правятся только постановкой. Вопросов стало четыре: два
 * («Что если аккаунт перестанет работать?» и «Что если я передумаю?»)
 * сняты там же.
 */
const QA = [
  {
    q: 'Нужен ли VPN?',
    a: 'VPN не нужен, ни для оплаты доступа, ни для прослушивания музыки',
  },
  {
    q: 'Как оплатить из России?',
    a: 'Оплата происходит с русской карты или СБП, после выбора тарифа и регистрации в личном кабинете',
  },
  {
    q: 'Можно ли слушать с нескольких устройств?',
    a: 'Владелец тарифа "на двоих" или "на троих" может приглашать новых участников или удалять существующих на странице подписки в Spotify',
  },
  {
    q: 'Сколько ждать после оплаты?',
    a: 'Сервис работает с 10:00 до 22:00 (по Москве), среднее время выдачи заказа составляет 5-10 минут',
  },
];

/** Линия отсчёта на касаниях: доля высоты экрана. */
const REF = 0.46;
/**
 * Радиус активности в долях шага между вопросами.
 *
 * ⚠️ ОН БОЛЬШЕ ПОЛОВИНЫ ШАГА, И ЭТО БЕЗОПАСНО. Двух строк разом
 * он дать не может: активным становится не «всякий, кто ближе
 * радиуса», а БЛИЖАЙШИЙ из них, а ближайший ровно один. Радиус
 * решает только одно — где блок начинается и где кончается.
 */
const REACH_OF_STEP = 0.55;
/**
 * Скорость строки, пикселей в секунду. «Спокойная»: та же величина
 * порядка, что у полосы преимуществ (Р-56, 70 px/с).
 */
const SPEED = 62;

export default function Faq() {
  const listRef = useRef<HTMLDivElement>(null);
  const base = useId();

  useEffect(() => {
    const list = listRef.current;
    const sc = scroller();
    if (!list || !sc || prefersReducedMotion()) return;

    let items: HTMLElement[] = [];
    let mids: number[] = [];
    let reach = 1;

    /* ДЛИТЕЛЬНОСТЬ КРУГА СЧИТАЕТСЯ ИЗ ШИРИНЫ КОПИИ. Замер один
       на раскладку; в кадре не читается ничего. */
    const measure = () => {
      const shift = sc.getBoundingClientRect().top - sc.scrollTop;
      items = Array.from(list.querySelectorAll<HTMLElement>('.qa__item'));
      mids = items.map((el) => {
        const r = el.getBoundingClientRect();
        return r.top - shift + r.height / 2;
      });
      for (const el of items) {
        const copy = el.querySelector<HTMLElement>('.qa__copy');
        if (!copy) continue;
        const w = copy.getBoundingClientRect().width;
        if (w > 1) el.style.setProperty('--dur', `${(w / SPEED).toFixed(2)}s`);
      }
      const step =
        mids.length > 1 ? (mids[mids.length - 1] - mids[0]) / (mids.length - 1) : sc.clientHeight;
      reach = step * REACH_OF_STEP;
    };

    measure();
    const offLayout = onLayoutChange(measure);

    /* На точном указателе строку ведёт `:hover` в CSS — подписываться
       на прокрутку там незачем и нельзя: два источника «кто активен»
       дали бы две бегущие строки разом. */
    if (finePointer()) {
      return () => {
        offLayout();
        for (const el of items) el.style.removeProperty('--dur');
      };
    }

    /* Кэш последнего состояния: смена активного трогает ровно два
       вопроса из шести. */
    const last: boolean[] = [];

    const read = (y: number) => {
      const line = y + sc.clientHeight * REF;
      /* АКТИВЕН БЛИЖАЙШИЙ, и это вся гарантия «одновременно бежит
         только одна строка»: ближайший по определению один. */
      let best = -1;
      let bd = Infinity;
      for (let i = 0; i < mids.length; i += 1) {
        const a2 = Math.abs(mids[i] - line);
        if (a2 < bd) {
          bd = a2;
          best = i;
        }
      }
      if (bd > reach) best = -1;
      for (let i = 0; i < items.length; i += 1) {
        const on = i === best;
        if (last[i] === on) continue;
        last[i] = on;
        if (on) items[i].setAttribute('data-on', '');
        else items[i].removeAttribute('data-on');
      }
    };

    const offScroll = onScrollY(read);
    return () => {
      offLayout();
      offScroll();
      for (const el of items) {
        el.removeAttribute('data-on');
        el.style.removeProperty('--dur');
      }
    };
  }, []);

  return (
    <section id="faq" className="section">
      <div className="shell">
        <SectionHead title="Ваши вопросы" center />

        <div ref={listRef} className="qa">
          {QA.map((item, i) => {
            const aid = `${base}-a-${i}`;
            return (
              <div key={item.q} className="qa__item">
                <h3 className="qa__q">{item.q}</h3>
                {/* ПОЛОСА ЛЕЖИТ ПОПЕРЁК ВОПРОСА и места в потоке
                    не занимает: раскладке двигаться нечем.
                    Появляется и уходит она прозрачностью. */}
                <div className="qa__tick">
                  <div className="qa__run">
                    {/* ⚠️ КОПИЙ ЧЕТЫРЕ, А НЕ ДВЕ, И ЭТО НЕ ЗАПАС «НА ВСЯКИЙ
                        СЛУЧАЙ». Ход круга — ровно одна копия; значит
                        к концу круга дорожка обязана закрывать полосу
                        ОСТАВШИМИСЯ копиями. При двух копиях в конце
                        круга справа открывалась пустота на полтысячи
                        пикселей — сторож поймал это растром. Условие:
                        (копий − 1) × ширина копии ≥ ширина полосы.
                        Первая копия несёт текст для скринридера,
                        остальные скрыты — ответ читается один раз. */}
                    <span className="qa__copy" id={aid}>
                      {item.a}
                    </span>
                    <span className="qa__copy" aria-hidden="true">
                      {item.a}
                    </span>
                    <span className="qa__copy" aria-hidden="true">
                      {item.a}
                    </span>
                    <span className="qa__copy" aria-hidden="true">
                      {item.a}
                    </span>
                  </div>
                </div>
              </div>
            );
          })}
        </div>
      </div>
    </section>
  );
}
