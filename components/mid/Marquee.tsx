/**
 * БЕГУЩАЯ СТРОКА — ОТДЕЛЬНАЯ ПОЛОСА ВО ВСЮ ШИРИНУ.
 *
 * До девятнадцатой итерации она шла ПОВЕРХ рядов тарифа и инвертировалась
 * по их чернилам. Ряды ушли вместе с приёмом разворота, и строка стала
 * тем, чем ей проще всего быть: полосой между блоком тарифов и блоком
 * порядка. Фон под ней теперь один и тёмный, поэтому выворотка не нужна
 * вовсе — а вместе с ней ушли слой `backdrop-filter`, обрезка по словам,
 * обмер живой строки и весь клиентский код. Компонент СЕРВЕРНЫЙ:
 * ни байта JavaScript, движение целиком на CSS.
 *
 * ── ШОВ ────────────────────────────────────────────────────────────────────
 * Текст выложен ДВАЖДЫ внутри дорожки шириной по содержимому, ход
 * анимации ровно −50 % её ширины. В конце круга на месте каждого знака
 * стоит точно такой же знак из второй копии, поэтому стыка не видно.
 * Мерить при этом нечего: 50 % считает сам браузер, и совпадение
 * получается по построению.
 *
 * ── ДОСТУПНОСТЬ ────────────────────────────────────────────────────────────
 * Движущийся текст читать нельзя, поэтому сама полоса скрыта от
 * скринридера, а те же формулировки лежат рядом обычным списком вне
 * экрана. При «уменьшить движение» полоса стоит.
 */
export default function Marquee({ items }: { items: string[] }) {
  const line = `${items.join(' · ')} · `;
  return (
    <div className="mq">
      <div className="mq__band" aria-hidden="true">
        <div className="mq__track">
          <span className="mq__copy">{line}</span>
          <span className="mq__copy">{line}</span>
        </div>
      </div>
      <ul className="sr-only">
        {items.map((t) => (
          <li key={t}>{t}</li>
        ))}
      </ul>
    </div>
  );
}
