'use client';

import { useEffect, useId, useRef } from 'react';
import { onLayoutChange } from '@/lib/scroll';
import { glyphShapes } from '@/lib/inkshape';

/**
 * БЕГУЩАЯ СТРОКА ПОВЕРХ РЯДОВ.
 *
 * Строка идёт ГОРИЗОНТАЛЬНО ПОВЕРХ ЧЕРНИЛ рядов и частично их перекрывает —
 * в этом весь приём, и в отступ между рядами её уводить нельзя. Там, где
 * она накрывает чернила, она ИНВЕРТИРУЕТСЯ, и делает это тем же
 * механизмом, что шапка: слой берёт свой собственный фон и прогоняет его
 * через ахроматическую выворотку, обрезанную по форме чернил (Р-47).
 * Никакого списка «где что лежит»: над тёмным полем строка выходит белой,
 * над белой литерой названия — чёрной, и решается это попиксельно.
 *
 * ── ПОЧЕМУ ДВА ЭЛЕМЕНТА, А НЕ ОДИН ─────────────────────────────────────────
 * `.mq__text` — живой текст. Он нужен трижды: как запасной вариант там,
 * где `backdrop-filter` не поддержан, как ЛИНЕЙКА для обмера фигуры
 * и как источник шрифтовых метрик. Под `@supports` он становится
 * прозрачным, и всё, что видно, рисует `.mq__ink`.
 *
 * Оба элемента крутит ОДНА И ТА ЖЕ анимация на СОБСТВЕННОМ трансформе.
 * Собственный трансформ backdrop root не создаёт, поэтому фон под слоем
 * настоящий; будь анимация на общем предке — фон оказался бы пустым
 * (те же грабли, что в Р-47).
 *
 * ── ПОЧЕМУ СЛОЙ НЕ ПРЯЧЕТСЯ ЧЕРЕЗ display ──────────────────────────────────
 * Элемент с `display: none` анимации не крутит, и, показавшись, начал бы
 * её с нуля — слой уехал бы от текста на полкруга. Поэтому слой рисуется
 * всегда, а пока фигура не собрана, его обрезка ПУСТА: пустой `clipPath`
 * не пропускает ничего, и стоит это ноль.
 *
 * ── ШОВ ────────────────────────────────────────────────────────────────────
 * Текст выложен ДВАЖДЫ, ход анимации ровно −50 % собственной ширины.
 * В конце круга на месте каждого знака стоит точно такой же знак
 * из второй копии, поэтому стыка не видно вовсе.
 *
 * ── ДОСТУПНОСТЬ ────────────────────────────────────────────────────────────
 * Движущийся текст читать нельзя, поэтому сама строка спрятана от
 * скринридера, а те же пять формулировок лежат рядом обычным списком
 * вне экрана. При «уменьшить движение» строка стоит.
 */
export default function Marquee({ items, className = '' }: { items: string[]; className?: string }) {
  const rootRef = useRef<HTMLDivElement>(null);
  const textRef = useRef<HTMLSpanElement>(null);
  const clipRef = useRef<SVGClipPathElement>(null);
  const clipId = `mq-c-${useId().replace(/[^a-zA-Z0-9-]/g, '')}`;

  /* Один текстовый узел на обе копии: обмер идёт по нему, а фигура
     собирается ПО СЛОВАМ. Политерно тут было бы полтысячи узлов ради
     точности, которой внутри слова и так неоткуда взяться: апрош в SVG
     и в HTML один и тот же. */
  const line = `${items.join(' · ')} · `;

  useEffect(() => {
    const root = rootRef.current;
    const text = textRef.current;
    const clip = clipRef.current;
    if (!root || !text || !clip) return;

    const build = () => {
      /* Отсчёт от бокса ЖИВОЙ строки: она в этот момент едет, и координаты,
         снятые от неподвижного предка, запеклись бы со сдвигом на фазу
         анимации. Разность с её собственным боксом фазы не знает. */
      const r = text.getBoundingClientRect();
      /* Ширина и высота уходят на КОРЕНЬ: от них считается и полоса
         самой строки, и габарит слоя, а ход анимации равен −50 %
         собственной ширины — у обоих она обязана быть одна. */
      root.style.setProperty('--mq-w', `${r.width.toFixed(2)}px`);
      root.style.setProperty('--mq-h', `${r.height.toFixed(2)}px`);
      const shapes = glyphShapes(text, r.left, r.top, 'word');
      clip.replaceChildren(...shapes);
      root.toggleAttribute('data-ink', shapes.length > 0);
    };

    build();
    const off = onLayoutChange(build);
    /* Шрифты доезжают после первой раскладки и двигают всю строку. */
    document.fonts?.ready.then(build).catch(() => {});
    return off;
  }, [line]);

  return (
    <div ref={rootRef} className={`mq ${className}`.trim()}>
      <span ref={textRef} className="mq__text" aria-hidden="true">
        {line + line}
      </span>
      <div className="mq__ink" aria-hidden="true" style={{ clipPath: `url(#${clipId})` }} />
      <svg className="mq__clip" aria-hidden="true" focusable="false">
        {/* Фигуры кладутся в обрезку напрямую: `<g>` в её модели
            содержимого нет, и завёрнутые в него контуры молча
            не обрезают ничего (Р-46). */}
        <clipPath ref={clipRef} id={clipId} clipPathUnits="userSpaceOnUse" />
      </svg>
      <ul className="sr-only">
        {items.map((t) => (
          <li key={t}>{t}</li>
        ))}
      </ul>
    </div>
  );
}
