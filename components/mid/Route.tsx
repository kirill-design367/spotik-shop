const STEP_GAP = [0, 1.0, 1.14, 0.86, 1.08];

/**
 * ⚠️ ПОЛОСА МЕЖДУ ШАГАМИ ВЫВОДИТСЯ ИЗ ТРЕБОВАНИЯ «БЕЗ УГЛОВАТЫХ
 * ПОВОРОТОВ», А НЕ ПОДБИРАЕТСЯ НА ГЛАЗ.
 *
 * «Угловатый поворот» — это маленький радиус кривизны, и он
 * считается. У кубика с вертикальными касательными на обоих концах,
 * вертикальной полосой `h` и горизонтальным путём `l`, при ручках
 * длиной `a·h`:
 *
 *     r = 1.5 · a² · h² / l
 *
 * Замер двадцать четвёртой итерации по растру пути: наименьший
 * радиус 4.5 px на 390 и 6.1 на 1920 — это и есть угол, а не дуга
 * (ядро ленты шириной 2.6 px, ореол 9…13). Формула сходится
 * с замером до десятых.
 *
 * Отсюда видно и то, почему подкрутить кривую нельзя: `l` задан
 * постановкой намертво — петля обязана уходить ЗА КРАЙ ЭКРАНА,
 * значит горизонтальный путь не меньше ширины экрана. Остаётся
 * единственный рычаг — полоса `h`, и она растёт как √r. Поэтому
 * блок порядка от мягких дуг НЕИЗБЕЖНО становится выше: это цена
 * приёма, а не наша неаккуратность.
 *
 * ⚠️ РУЧКИ ДЛИННЫЕ (0.72 полосы), И ЭТО ТОЖЕ ИЗ ФОРМУЛЫ: радиус
 * растёт как a². Выше 0.8 подниматься нельзя — сумма двух ручек
 * подходит к 1.6, и середина дуги вырождается в горизонтальную
 * полку. При 0.72 вертикальная скорость в середине ещё 0.42 полосы
 * против 2.16 на концах.
 *
 * ⚠️ ДОЛЯ ПОЛОСЫ У ДЛИННОГО ПЛЕЧА ОГРАНИЧЕНА 0.66, А НЕ 0.82.
 * Раньше плечи делили полосу по доле горизонтального пути, чтобы
 * НАКЛОН у обеих дуг был один. Но короткому плечу от этого
 * доставалось 0.18 полосы — четырнадцать пикселей на 390, —
 * и радиус там падал до полутора. Ровный наклон глазу не нужен,
 * а угол виден.
 */
const R_MIN = 15;
const HANDLE = 0.72;
const SHARE_MAX = 0.66;
const SHARE_MIN = 1 - SHARE_MAX;
/**
 * Множитель кегля. Вразнобой: ни по возрастанию, ни по убыванию.
 *
 * ⚠️ С СОРОК ПЕРВОЙ ИТЕРАЦИИ ПО НЕМУ ЖИВЁТ ТОЛЬКО ЦИФРА. Текст шага
 * от места в таблице больше не зависит вовсе: он МАЛЕНЬКИЙ у всех
 * и вырастает у того шага, который сейчас в середине экрана. Рельеф
 * при этом цел — сторона, отступ и отбой не тронуты, а разнобой
 * кегля остался в номерах.
 *
 * Цифру трогать нельзя по прямой постановке, и причина у запрета
 * своя: с `.rstep__num` снимается ТОЧКА МАРШРУТА (Р-76). Менялся бы
 * её кегль в кадре — вместе с ним ездил бы и центр цифры, а лента
 * нарисована по центрам, снятым один раз при раскладке: линия
 * перестала бы проходить сквозь номер.
 */
const STEP_SIZE = [1.12, 0.78, 1.32, 0.74, 0.96];
/**
 * ГРАНИЦЫ ДИНАМИКИ — КРАЯ ТОЙ ЖЕ ТАБЛИЦЫ, А НЕ НОВЫЕ ЧИСЛА.
 * Постановка названа ими: «маленький, как сейчас у самого мелкого
 * шага» и «вырастает до размера, как сейчас у самого крупного».
 * Выводим, а не выписываем: правка таблицы не должна молча
 * разойтись с размахом роста.
 */
const SIZE_MIN = Math.min(...STEP_SIZE);
const SIZE_MAX = Math.max(...STEP_SIZE);
/** «Уменьшить движение»: динамики нет, все шаги в одном среднем. */
const SIZE_MID = (SIZE_MIN + SIZE_MAX) / 2;
/**
 * ОПИСАНИЕ ИДЁТ ЗА КЕГЛЕМ ШАГА, НО ВДВОЕ ТИШЕ, И ЭТО НЕ УКРАШЕНИЕ.
 * Ровный множитель на весь текст невозможен арифметически: у минимума
 * 0.56 от максимума, и описание, посчитанное от читаемого низа,
 * выросло бы в середине до кегля заголовка — иерархия пропала бы
 * вовсе. Считанное же от максимума оно ушло бы внизу в 8.6 px.
 * Поэтому у описания свой, сжатый размах — тот же, что стоял
 * у постоянного кегля до этой итерации.
 */
const descAt = (ss: number) => 0.7 + 0.3 * ss;
/**
 * ПОЛУШИРИНА ОКНА РОСТА — ДОЛЯ РАССТОЯНИЯ ДО БЛИЖАЙШЕГО СОСЕДА.
 * Не доля экрана: шаги стоят неравномерно (отбой идёт по таблице
 * рельефа), и одно число на всех давало бы то два выросших разом,
 * то мёртвую зону между ними. От соседа окно подстраивается само.
 *
 * При 0.65 на полпути между шагами оба соседа подняты на 13 %
 * размаха — передача мягкая, без кадра, где не происходит ничего,
 * и без двух крупных шагов сразу.
 */
const GROW_WIN = 0.65;
/**
 * Колокол роста: единица в центре, ноль на краю окна, И ПРОИЗВОДНАЯ
 * НОЛЬ НА ОБОИХ КОНЦАХ. Второе важнее первого — на входе в окно
 * и на выходе из него не должно быть излома, иначе рост читается
 * как срабатывание по порогу, а постановка требует обратного.
 */
const grow = (u: number) => (u >= 1 ? 0 : (1 + Math.cos(Math.PI * u)) / 2);
/** Насколько вершина петли заходит за край экрана, доля выноса холста. */
const LOOP_OUT = 0.55;
/** Вынос холста за блок, доля ширины экрана. */
const overOf = (vw: number, narrow: boolean) =>
  Math.max(56, Math.min(200, vw * (narrow ? 0.2 : 0.13)));
/**
 * Полоса между шагами, при которой самый крутой поворот не круче
 * `R_MIN`. Зависит ТОЛЬКО от ширины экрана, поэтому считается
 * до всякой раскладки — а раскладку она как раз и задаёт.
 */
const gapOf = (vw: number, narrow: boolean) => {
  const l = vw + overOf(vw, narrow) * (1 + LOOP_OUT);
  const h = Math.sqrt((R_MIN * l) / (1.5 * HANDLE * HANDLE));
  /* Полоса делится между плечами, длинному достаётся SHARE_MAX;
     плюс воздух до текста с обеих сторон. */
  return h / SHARE_MAX + 2 * CLEAR;
};
/** На узком экране вынос холста меньше, но за край петля уходит всё равно. */
const NARROW = 720;
/** Воздух между текстом шага и местом, где линия начинает уходить вбок. */
const CLEAR = 26;

