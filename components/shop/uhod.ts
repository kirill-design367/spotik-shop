'use client';

import { useEffect, useRef } from 'react';

/**
 * УХОД НА ПЛАТЁЖНУЮ ФОРМУ — БРАУЗЕРОМ, А НЕ РОУТЕРОМ NEXT.
 *
 * ⚠️ ЭТО ПОЧИНКА НАСТОЯЩЕЙ ПОЛОМКИ, А НЕ ПЕРЕСТРАХОВКА. Нажатие
 * «назад» со страницы оплаты Робокассы роняло сайт с «Application
 * error: a client-side exception has occurred». Причина в том, что
 * серверное действие уходило на ЧУЖОЙ домен через `redirect()`:
 * обычным перенаправлением так нельзя, поэтому Next отдаёт адрес
 * своему роутеру, и тот двигает `window.location` сам — а в истории
 * остаётся запись, за которой лежит ответ ДЕЙСТВИЯ, а не страницы.
 * На возврате роутер пытается применить её как дерево страницы
 * и падает.
 *
 * Здесь навигация идёт обычным `location.assign` с обычной страницы:
 * в истории остаётся GET-запрос оформления (или кабинета), и возврат
 * открывает её как любую другую. Роутер Next в этом не участвует
 * вовсе — значит и ломаться ему нечего.
 *
 * ⚠️ ЗАЩЁЛКА ОБЯЗАТЕЛЬНА. Состояние действия живёт до следующей
 * отправки формы, и без неё повторная отрисовка (а её вызывает любое
 * нажатие на странице) уводила бы человека на оплату снова.
 */
export function useUhodNaOplatu(kuda: string | undefined): void {
  const ushli = useRef(false);
  useEffect(() => {
    if (!kuda || ushli.current) return;
    ushli.current = true;
    window.location.assign(kuda);
  }, [kuda]);
}
