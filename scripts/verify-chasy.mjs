/**
 * ЧАСЫ РАБОТЫ: ПОДМЕНЯЕМ ВРЕМЯ И СМОТРИМ, ЧТО ВЫХОДИТ.
 *
 * ⚠️ ЗАПУСКАЕТСЯ РУКАМИ И НЕ СТОИТ В ВЫКЛАДКЕ — закон 47 называет
 * пять её шагов поимённо, и достраивать список от себя нельзя.
 * В выкладке живое поведение проверяет `verify-shop`: он сравнивает
 * плашку на оформлении с НЕЗАВИСИМО посчитанным московским часом,
 * а в какой именно час его прогнали, решает расписание раннера.
 * Здесь же проверяются ГРАНИЦЫ — 09:59, 10:00, 21:59, 22:00 —
 * и зима: перевода часов в России нет с 2014 года, и если таблица
 * зон об этом однажды передумает, узнать об этом надо здесь.
 *
 *     node --experimental-strip-types scripts/verify-chasy.mjs
 */
import { chasPoMoskve, rabocheeVremya, CHASY_SLOVAMI, CHASY_OT_DO } from '../lib/chasy.ts';
const p = (iso) => new Date(iso);
const sluchai = [
  ['2026-09-25T06:30:00Z', 9],   // 09:30 МСК — до открытия
  ['2026-09-25T07:00:00Z', 10],  // 10:00 МСК — ровно открытие
  ['2026-09-25T12:00:00Z', 15],
  ['2026-09-25T18:59:00Z', 21],  // 21:59 МСК — ещё работаем
  ['2026-09-25T19:00:00Z', 22],  // 22:00 МСК — ровно закрытие
  ['2026-09-25T21:30:00Z', 0],   // 00:30 МСК следующих суток
  ['2026-01-15T07:00:00Z', 10],  // зима: перевода часов в России нет
];
console.log('строка:', CHASY_SLOVAMI, '| только часы:', CHASY_OT_DO);
let bad = 0;
for (const [iso, zhdyom] of sluchai) {
  const h = chasPoMoskve(p(iso));
  const rab = rabocheeVremya(p(iso));
  const ok = h === zhdyom;
  if (!ok) bad += 1;
  console.log(`${ok ? 'OK  ' : 'СБОЙ'} ${iso} → ${String(h).padStart(2, '0')}:xx МСК, рабочее=${rab ? 'да' : 'нет'} (ждали час ${zhdyom})`);
}
// Границы: 09:59 нет, 10:00 да, 21:59 да, 22:00 нет
const gr = [
  ['2026-09-25T06:59:00Z', false],
  ['2026-09-25T07:00:00Z', true],
  ['2026-09-25T18:59:00Z', true],
  ['2026-09-25T19:00:00Z', false],
];
for (const [iso, zhdyom] of gr) {
  const v = rabocheeVremya(p(iso));
  const ok = v === zhdyom;
  if (!ok) bad += 1;
  console.log(`${ok ? 'OK  ' : 'СБОЙ'} граница ${iso}: рабочее=${v}, ждали ${zhdyom}`);
}
console.log(bad ? `ПРОВАЛ: ${bad}` : 'ЧАСЫ СЧИТАЮТСЯ ПО МОСКВЕ ВЕРНО');
process.exit(bad ? 1 : 0);
