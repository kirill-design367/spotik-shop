/**
 * ОТПЕЧАТОК СОСТОЯНИЯ КАБИНЕТА — для страницы, которая обновляется
 * сама. Сам отпечаток считает `lib/server/otpechatok.ts`: его берёт
 * и страница при отрисовке, и этот опрос.
 *
 * ⚠️ 401, А НЕ ПУСТОЙ ОТВЕТ, когда сессии нет. Опрос обязан
 * прекратиться и сказать человеку, что надо войти заново, —
 * постановка. Пустой ответ был бы неотличим от «пока ничего
 * не менялось», и вкладка молча опрашивала бы сервер до вечера.
 *
 * ⚠️ ЭТО ЧЕТВЁРТЫЙ МАРШРУТ `/api`, И БОЛЬШЕ ИХ БЫТЬ НЕ ДОЛЖНО
 * без причины: всё остальное на сайте — серверные действия. Здесь
 * маршрут нужен потому, что спрашивает его таймер в браузере,
 * а серверное действие — это POST с телом формы и перерисовкой,
 * то есть заметно дороже одной короткой строки.
 */

import { ktoKlient } from '@/lib/server/auth';
import { bazaEst } from '@/lib/server/db';
import { otpechatokKabineta } from '@/lib/server/otpechatok';

export const dynamic = 'force-dynamic';

export async function GET(): Promise<Response> {
  /* ⚠️ БАЗА ПРОВЕРЯЕТСЯ ПЕРВОЙ, И ЭТО НЕ ПОРЯДОК РАДИ ПОРЯДКА.
     `ktoKlient` спрашивает сессию у базы и при недоступной базе
     тихо отдаёт `null` — то есть ровно то же, что и при кончившейся
     сессии. Спроси мы его раньше, человеку с ЖИВОЙ сессией сказали бы
     «войдите заново» на всякое моргание PostgreSQL, а войти было бы
     некуда: вход тоже требует базы. Пустой отпечаток честнее —
     он значит «сравнивать пока не с чем», и опрос продолжается. */
  if (!bazaEst()) return Response.json({ otpechatok: '', dostupov: 0 });
  const kto = await ktoKlient();
  if (!kto) return new Response('need login', { status: 401 });
  return Response.json(await otpechatokKabineta(kto.userId));
}
