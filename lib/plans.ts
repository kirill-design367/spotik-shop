/**
 * НАЗВАНИЕ ТАРИФА НА ЯЗЫКЕ СОТРУДНИКА.
 *
 * ⚠️ ЖИВЁТ ЗДЕСЬ, А НЕ В `lib/server/catalog.ts`, И ЭТО ВЫНУЖДЕННО:
 * каталог ходит в базу, а звать эту функцию надо и из КЛИЕНТСКИХ
 * кусков админки (очередь обновляется сама). Состав тарифов и так
 * лежит здесь — значит и имена оттуда же.
 *
 * ⚠️ НЕИЗВЕСТНЫЙ ТАРИФ ОТДАЁТ СВОЙ `id`, А НЕ ПУСТОТУ. Заказ, чей
 * тариф сняли из каталога, обязан остаться читаемым в админке:
 * `solo` понятнее, чем пустая ячейка.
 */
export function imyaTarifa(planId: string, en: boolean): string {
  const p = PLANS.find((x) => x.id === planId);
  if (!p) return planId;
  return en ? p.nameEn : p.name;
}

/**
 * НАЗВАНИЯ ТАРИФОВ, ЗАДАННЫЕ В АДМИНКЕ.
 *
 * ⚠️ ЧИТАЕТ ИХ БАЗА (`lib/server/imena.ts`), А ПРИМЕНЯЕТ ЭТА ФУНКЦИЯ,
 * и живёт она здесь по той же причине, что и `imyaTarifa`: звать её
 * надо и из КЛИЕНТСКИХ кусков админки, где очередь обновляется сама,
 * а туда серверный модуль не протащить. Карта имён приезжает пропом.
 *
 * ⚠️ КАРТЫ НЕТ ИЛИ ТАРИФА В НЕЙ НЕТ — РАБОТАЕТ ИМЯ ИЗ КОДА. База
 * недоступна, тариф сняли из каталога, страницу собрали без имён:
 * во всех трёх случаях надпись обязана остаться читаемой.
 *
 * ⚠️ КОРОТКОЕ ИМЯ СЮДА НЕ ХОДИТ ВОВСЕ. Оно стоит только на карточке
 * тарифа — на главной и на сертификатах, — а это места КЛИЕНТА,
 * и приезжает оно туда каталогом. В админке, в боте и в письмах
 * тариф называется полным именем (постановка сорок третьей
 * итерации: «полное — везде, где сейчас стоит полное»).
 */
export type ImenaTarifov = Record<string, { name: string; nameEn: string; short: string }>;

export function imyaTarifaIz(imena: ImenaTarifov | null | undefined, planId: string, en: boolean): string {
  const o = imena?.[planId];
  if (!o) return imyaTarifa(planId, en);
  return en ? o.nameEn : o.name;
}

/** Срок на языке сотрудника: «Полгода» / «6 months». */
export function srokDlyaSotrudnika(period: number, en: boolean): string {
  const p = PERIODS.find((x) => x.key === period);
  if (!p) return en ? `${period} months` : `${period} мес`;
  return en ? p.en : p.label;
}

/** Он же кратко: в русском «6 мес», в английском та же форма. */
export function srokKratkoDlyaSotrudnika(period: number, en: boolean): string {
  const p = PERIODS.find((x) => x.key === period);
  if (!p) return en ? `${period} months` : `${period} мес`;
  return en ? p.en : p.short;
}

/** 1 490 вместо 1490 — разряды обязательны, иначе цифра не читается. */
export function formatPrice(v: number): string {
  return v.toLocaleString('ru-RU').replace(/ /g, ' ');
}

/** Экономия относительно помесячной оплаты того же тарифа. */
export function savings(plan: Plan, months: PeriodKey): number {
  const monthly = plan.prices[1];
  const total = plan.prices[months];
  if (!monthly || !total || months === 1) return 0;
  return monthly * months - total;
}

