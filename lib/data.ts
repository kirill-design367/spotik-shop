/**
 * Настоящая ли это календарная дата `ГГГГ-ММ-ДД`.
 *
 * ⚠️ ОБРАЗЦА МАЛО, И `Date.parse` ТОЖЕ НЕ СУДЬЯ. «2026-02-31» проходит
 * образец, и V8 отвечает на него числом — молча переносит в март, —
 * а база падает на нём ошибкой. Значения приходят из форм и адресной
 * строки, то есть правятся в браузере, и на такой правке раздел
 * отвечал бы ошибкой сервера. Дата годится, только если она переживает
 * разбор и обратную запись без изменений. Годы — в пределах, где
 * у сервиса вообще бывают даты: год ноль база не примет вовсе.
 */
export function nastoyashchayaData(v: string | null | undefined): v is string {
  if (!v || !/^\d{4}-\d{2}-\d{2}$/.test(v)) return false;
  const god = Number(v.slice(0, 4));
  if (god < 2000 || god > 2100) return false;
  const d = new Date(v + 'T00:00:00Z');
  return !Number.isNaN(d.getTime()) && d.toISOString().slice(0, 10) === v;
}
