/**
 * Отзыв: правила, общие для формы и сервера.
 *
 * ⚠️ ОДИН ФАЙЛ НА ОБЕ СТОРОНЫ, как у почты с паролем (`lib/proverka.ts`)
 * и у промокода (`lib/promokod.ts`): форма показывает отказ заранее,
 * а сервер проверяет то же самое заново — форма правится в браузере
 * за секунду. Две копии правил разошлись бы на первой же правке,
 * и сервер отказывал бы в том, что форма пропустила.
 *
 * Пределы:
 *   • имя или ник — до 60 знаков, одной строкой;
 *   • текст — до 600 знаков (поправка после рецензии: отзыв в полторы
 *     тысячи знаков набран крупно, все карточки «Сейчас играет» лежат
 *     в одной ячейке, и один длинный отзыв делал экран выше телефона
 *     для всех остальных).
 *
 * ⚠️ ЗНАКИ СЧИТАЮТСЯ ПО КОДОВЫМ ТОЧКАМ (`Array.from`), а не по длине
 * строки JavaScript: так же считает база (`char_length`), и смайлик
 * у обеих сторон весит один знак, а не два.
 */

export const IMYA_MAX = 60;
export const TEKST_MAX = 600;
/** Сколько опубликованных нужно, чтобы блок появился на главной. */
export const POROG_POKAZA = 3;
/** Сколько опубликованных берётся на главную — первые по порядку. */
export const NA_GLAVNOY = 12;

/** Число знаков так, как его считает база. */
export function znakov(s: string): number {
  return Array.from(s).length;
}

/**
 * Имя одной строкой: управляющие знаки и переводы строк — в пробел,
 * пробелы подряд — в один. Имя стоит строкой исполнителя, и перенос
 * внутри него читался бы как два имени.
 */
export function chistoeImya(s: string | null | undefined): string {
  return (s ?? '')
    .replace(/[\u0000-\u001f\u007f]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Текст: абзацы сохраняются (человек мог писать с переносами),
 * но не больше одной пустой строки подряд; управляющие знаки, кроме
 * перевода строки, выбрасываются.
 */
export function chistyTekst(s: string | null | undefined): string {
  return (s ?? '')
    .replace(/\r\n?/g, '\n')
    .replace(/[\u0000-\u0009\u000b-\u001f\u007f]+/g, ' ')
    .replace(/[ \t]+\n/g, '\n')
    .replace(/\n{3,}/g, '\n\n')
    .replace(/[ \t]{2,}/g, ' ')
    .trim();
}

/** Что не так с именем; `null` — всё верно. Слова — для формы. */
export function bedaImeni(imya: string): string | null {
  const v = chistoeImya(imya);
  if (!v) return 'Укажите имя или ник';
  if (znakov(v) > IMYA_MAX) return `Имя — не длиннее ${IMYA_MAX} знаков`;
  return null;
}

export function bedaTeksta(tekst: string): string | null {
  const v = chistyTekst(tekst);
  if (!v) return 'Напишите отзыв';
  if (znakov(v) > TEKST_MAX) return `Отзыв — не длиннее ${TEKST_MAX} знаков`;
  return null;
}
