import { ZONA_MSK } from '@/lib/chasy';

/** Дата и время по Москве одной строкой. */
export function poMoskve(kogda: string | Date | null | undefined, en = false): string {
  if (!kogda) return '';
  const d = typeof kogda === 'string' ? new Date(kogda) : kogda;
  if (Number.isNaN(d.getTime())) return '';
  try {
    return d.toLocaleString(en ? 'en-GB' : 'ru-RU', {
      timeZone: ZONA_MSK,
      dateStyle: 'short',
      timeStyle: 'short',
    });
  } catch {
    const m = new Date(d.getTime() + 3 * 60 * 60 * 1000);
    const dv = (n: number) => String(n).padStart(2, '0');
    return `${dv(m.getUTCDate())}.${dv(m.getUTCMonth() + 1)}.${m.getUTCFullYear()}, ${dv(m.getUTCHours())}:${dv(m.getUTCMinutes())}`;
  }
}
