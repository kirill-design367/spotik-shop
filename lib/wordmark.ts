/**
 * ВОРДМАРК-СКОБКИ: морф контуров.
 *
 * Слово SPOTIK — не текст. Это два набора точек контуров, запечённых на этапе
 * сборки из вариативного бинарника Unbounded (см. scripts/build-wordmark.py),
 * между которыми рантайм интерполирует по прогрессу скролла.
 *
 * ── ПОЧЕМУ НЕ ТЕКСТ И НЕ ОСИ ────────────────────────────────────────────────
 * В прошлой итерации приём жил на осях вариативного шрифта. Замер показал, что
 * сам растр глифов браузер НЕ огрубляет: при непрерывном ходе оси YTUC высота
 * чернил меняла значение почти на каждом шаге — 204 различных высоты
 * на 233 шага оси, площадки максимум в два шага при ожидаемых 0.9 px на шаг.
 *
 * Зато огрубляется РАСКЛАДКА. Ширина слова обязана быть постоянной, а фактически
 * за 417 кадров непрерывного скролла она приняла всего 51 различное значение
 * и гуляла в пределах 2226.94…2228.31 px: браузер округляет метрики глифов,
 * и внутренние позиции литер идут ступеньками. Плюс доводчик трекинга
 * из прошлой итерации давал разовый скачок до 1.4 px в момент остановки.
 *
 * Контуры убирают всё это разом: нет раскладки, нет округления метрик,
 * нет доводчика. Координаты — числа с плавающей точкой, растеризуются напрямую.
 *
 * ── ЧТО ЗДЕСЬ БОЛЬШЕ НЕ ДЕЛАЕТСЯ ───────────────────────────────────────────
 * Ни одного чтения геометрии DOM — ни при монтировании, ни в кадре. Калибровка
 * прошлой итерации (таблица ширин, пробный элемент, трекинг-доводчик) исчезла
 * целиком: ширина слова постоянна по построению.
 */
import {
  WM_CONTOURS,
  WM_OPS,
  WM_OPEN,
  WM_TIGHT,
  WM_WIDTH,
  WM_CAP_OPEN,
  WM_CAP_TIGHT,
  WM_BOX_TOP,
  WM_BOX_BOTTOM,
} from './wordmark.data';

export { WM_WIDTH, WM_CAP_OPEN, WM_CAP_TIGHT, WM_BOX_TOP, WM_BOX_BOTTOM };

/**
 * Насколько слово шире вьюпорта. Первая и последняя литеры обязаны уходить
 * за экран — это не смягчается ни на одном размере.
 */
export const OVERSCAN = 1.16;

/** Высота рамки чернил в нормированных единицах: включает свес S и O. */
export const WM_BOX_HEIGHT = WM_BOX_BOTTOM - WM_BOX_TOP;

/** Смягчение прогресса: сжатие начинается спокойно и доходит до края решительно. */
export function ease(t: number): number {
  return t * t * (3 - 2 * t);
}

/** Высота прописной на прогрессе t, в нормированных единицах. */
export function capAt(t: number): number {
  return WM_CAP_OPEN + (WM_CAP_TIGHT - WM_CAP_OPEN) * ease(t);
}

/* ────────────────────────────────────────────────────────────────────────────
 * ПОСТРОЕНИЕ ПУТИ
 *
 * Точность 0.001 нормированной единицы. При ширине слова 1000 единиц и
 * типичном экране это около 0.002 px — на порядок мельче внутренней сетки
 * растеризатора (1/256 px у Skia). То есть огрубление здесь заведомо не то
 * место, где движение могло бы стать ступенчатым.
 * ────────────────────────────────────────────────────────────────────────── */

const N = WM_OPEN.length;
/** Рабочий буфер: выделяется один раз, в кадре не аллоцируется ничего. */
const cur = new Float32Array(N);

function num(v: number): string {
  return String(Math.round(v * 1000) / 1000);
}

/**
 * Путь слова на прогрессе t. Команды и их порядок одинаковы у обоих
 * состояний, поэтому строка всегда одной структуры — меняются только числа.
 */
export function buildPath(t: number): string {
  const e = ease(t);
  for (let i = 0; i < N; i += 1) cur[i] = WM_OPEN[i] + (WM_TIGHT[i] - WM_OPEN[i]) * e;

  let d = '';
  let o = 0;
  let p = 0;
  for (let c = 0; c < WM_CONTOURS.length; c += 1) {
    const n = WM_CONTOURS[c];
    d += `M${num(cur[p])} ${num(cur[p + 1])}`;
    p += 2;
    for (let i = 0; i < n; i += 1) {
      if (WM_OPS[o] === 1) {
        d += `L${num(cur[p])} ${num(cur[p + 1])}`;
        p += 2;
      } else {
        d += `Q${num(cur[p])} ${num(cur[p + 1])} ${num(cur[p + 2])} ${num(cur[p + 3])}`;
        p += 4;
      }
      o += 1;
    }
    d += 'Z';
  }
  return d;
}

/** Рамка для viewBox: слово целиком, вместе со свесом под базовой линией. */
export const VIEW_BOX = `0 ${WM_BOX_TOP} ${WM_WIDTH} ${WM_BOX_HEIGHT}`;

/**
 * Габариты слоя в долях ширины вьюпорта. Считаются здесь, чтобы серверная
 * разметка уже была правильного размера: вордмарк рисуется с первого кадра,
 * до всякого JavaScript, и не даёт сдвига макета.
 */
export const LAYER_WIDTH_VW = OVERSCAN;
export const LAYER_HEIGHT_VW = (OVERSCAN * WM_BOX_HEIGHT) / WM_WIDTH;

/** Где внутри рамки лежит верх прописных раскрытого состояния, в долях высоты. */
export const CAP_TOP_FRACTION = (-WM_CAP_OPEN - WM_BOX_TOP) / WM_BOX_HEIGHT;

/**
 * Насколько верх слоя выше линии прописных, в долях ширины вьюпорта.
 *
 * Это нужно прямо в серверной разметке. Если поставить слой на место
 * только из JS, браузер засчитает переезд как сдвиг макета — Lighthouse
 * ловил ровно это: слой появлялся у верха секции и после гидратации
 * опускался на --wm-top. Теперь смещение записано в разметке той же
 * формулой, что и в JS, и первый кадр совпадает с установившимся.
 */
export const CAP_TOP_VW = CAP_TOP_FRACTION * LAYER_HEIGHT_VW * 100;
