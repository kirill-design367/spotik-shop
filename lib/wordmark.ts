/**
 * ВОРДМАРК-СКОБКИ: морф контуров.
 *
 * Слово SPOTIK — не текст. Это два набора точек контуров, запечённых на этапе
 * сборки из вариативного бинарника Unbounded (см. scripts/build-wordmark.py),
 * между которыми рантайм интерполирует по прогрессу скролла.
 *
 * ── ШЕСТЬ УСЛОВИЙ, КОТОРЫЕ ЗДЕСЬ ДЕРЖАТСЯ ──────────────────────────────────
 *   1. верх чернил неподвижен — слово меняется только вниз;
 *   2. слово не обрезано краями, отступ WM_INSET с каждой стороны;
 *   3. ширина и положение каждой литеры постоянны;
 *   4. высота прописной падает в 1.712 раза;
 *   5. горизонтальные штрихи худеют в 2.833 раза;
 *   6. вертикальные штрихи не меняются.
 *
 * Условия 2, 3 и 6 держатся не проверкой, а построением: у сжатого состояния
 * координаты x ТОЖДЕСТВЕННО равны координатам раскрытого (сжатое собрано
 * скрещиванием — x у жирного начертания, y у светлого). Интерполяция между
 * равными числами их не меняет, поэтому x стоит на каждом кадре морфа,
 * а не только на концах.
 *
 * Условие 1 держится тем, что у обоих состояний верх чернил лежит на y = 0,
 * и самая верхняя точка у них ОДНА И ТА ЖЕ — сборка это проверяет перебором
 * по всему ходу. Значит слой можно поставить один раз и больше не двигать.
 *
 * ── ПОЧЕМУ НЕ ТЕКСТ И НЕ ОСИ ────────────────────────────────────────────────
 * Приём жил на осях вариативного шрифта в первой итерации. Замер показал, что
 * сам растр глифов браузер НЕ огрубляет, зато огрубляет РАСКЛАДКУ: ширина
 * слова, обязанная быть постоянной, за 417 кадров приняла 51 различное
 * значение и гуляла в пределах 2226.94…2228.31 px — браузер округляет метрики
 * глифов. Контуры убирают это разом: раскладки нет, округлять нечего.
 *
 * ── ЧТО ЗДЕСЬ НЕ ДЕЛАЕТСЯ ──────────────────────────────────────────────────
 * Ни одного чтения геометрии DOM — ни при монтировании, ни в кадре.
 */
import {
  WM_CONTOURS,
  WM_OPS,
  WM_OPEN,
  WM_TIGHT,
  WM_WIDTH,
  WM_CAP_OPEN,
  WM_CAP_TIGHT,
  WM_BOX_HEIGHT,
  WM_BOTTOM_OPEN,
  WM_BOTTOM_TIGHT,
  WM_CAP_TOP_OPEN,
  WM_LETTER_CONTOURS,
} from './wordmark.data';

export { WM_WIDTH, WM_CAP_OPEN, WM_CAP_TIGHT, WM_BOX_HEIGHT };

/**
 * Отступ слова от края экрана, в долях ширины вьюпорта.
 *
 * Замер эталона на 1920: левый край чернил на 12 px, правый на 1907 —
 * то есть около 0.65 % ширины с каждой стороны. Обрезки краями больше нет,
 * первая и последняя литеры видны целиком.
 */
export const WM_INSET = 0.0065;

/**
 * Ширина слоя в долях ширины ОБЛАСТИ СОДЕРЖИМОГО.
 *
 * Не вьюпорта. В Chrome `100vw` включает ширину классической полосы
 * прокрутки, а раскладка идёт по области содержимого, которая уже примерно
 * на 15 px. Слово в vw получалось шире места, правый отступ съедался
 * целиком и уходил в минус — литеру K обрезало. Замерено на 1920 с полосой
 * 15 px: отступ слева 12.47 px, справа −2.50 px.
 *
 * Поэтому величина применяется в единицах контейнерного запроса (`cqw`):
 * это ровно 1 % ширины СОДЕРЖИМОГО ближайшего предка-контейнера, полоса
 * прокрутки туда не входит. Контейнерами объявлены секции хиро и футера.
 */
export const LAYER_WIDTH = 1 - WM_INSET * 2;

/**
 * Поле над словом, в долях высоты прописной.
 *
 * Нужно входу букв: литера перелетает выше конечного положения, и если
 * над ней нет запаса, перелёт срежется собственной рамкой SVG, а то,
 * что выше, закроет непрозрачная навигация. Поле берёт запас больше
 * перелёта, поэтому подскок виден целиком.
 *
 * Заодно это просто воздух между навигацией и словом.
 */
export const PAD_RATIO = 0.05;
export const WM_PAD = WM_CAP_OPEN * PAD_RATIO;

/** Высота перелёта при входе, в долях высоты прописной (задание: 2…4 %). */
export const ENTER_OVERSHOOT_RATIO = 0.03;
export const WM_OVERSHOOT = WM_CAP_OPEN * ENTER_OVERSHOOT_RATIO;

/** Полная высота рамки: поле сверху плюс чернила. */
export const WM_VIEW_HEIGHT = WM_PAD + WM_BOX_HEIGHT;

/** Поле сверху в долях высоты чернил — этим футер подтягивает слово вровень. */
export const PAD_OVER_INK = WM_PAD / WM_BOX_HEIGHT;

/**
 * Ход скролла, за который слово проходит весь морф, в долях высоты экрана.
 *
 * Было 1.0 — ровно экран, и это читалось как сопротивление: человек крутил
 * колесо, а страница стояла, пока литеры дожимались. Стало 0.55: слово
 * досжимается вдвое быстрее, и секция ровно на столько же короче, поэтому
 * после дожатия страница едет дальше без паузы.
 *
 * Отсюда же берётся высота секции хиро (100svh + это), поэтому прогресс
 * гарантированно доходит до единицы ровно в тот момент, когда хиро
 * отлипает и уходит с экрана.
 */
export const MORPH_TRAVEL = 0.55;

/**
 * СРЕЗ ВЕРХУШЕК ЛИТЕР В ФУТЕРЕ, в долях высоты прописной.
 *
 * Зелёное поле футера начинается не наверху экрана, а ровно у слова: его
 * верхняя граница проходит чуть ниже линии прописных, поэтому верхушки
 * литер оказываются срезаны. Срез делает ГРАНИЦА ПОЛЯ — тот же элемент,
 * который заливает зелёным, режет своим верхним краем. Геометрия контуров
 * при этом не меняется ни на единицу: шесть условий её не отдают.
 *
 * Отсчёт идёт от ЛИНИИ ПРОПИСНЫХ (верх плоских P, T, I, K), а не от верха
 * чернил. Причина арифметическая: круглые S и O выходят выше линии
 * прописных на 1.93 % высоты прописной — это овершут рисунка. Если
 * отсчитывать от верха чернил, то любая величина внутри ориентира 1…2 %
 * съедает только этот овершут, плоские литеры не задевает вовсе (при 2 %
 * им достаётся 0.07 % высоты прописной — 0.2 пикселя на 1920), и срез
 * читается не как приём, а как «у круглых литер пропал овершут».
 * От линии прописных величина работает на всех шести литерах сразу.
 *
 * Величина одна и выражена в долях высоты прописной, поэтому на 390, 1920
 * и 2560 срез выглядит одинаково: и высота прописной, и срез масштабируются
 * одним и тем же вертикальным масштабом слоя.
 */
export const FOOTER_CUT_RATIO = 0.015;

/**
 * Тот же срез в долях ВЫСОТЫ ЧЕРНИЛ — в этих единицах живёт CSS: высота
 * слоя (--wm-h) задана по чернилам, и опустить границу поля нужно от их
 * верха. Складываются две величины: овершут круглых литер (от верха чернил
 * до линии прописных) и сам срез.
 */
export const CUT_OVER_INK =
  (WM_CAP_TOP_OPEN + WM_CAP_OPEN * FOOTER_CUT_RATIO) / WM_BOX_HEIGHT;


/**
 * Во сколько раз слой выше своих чернил.
 *
 * Высоту слоя задаёт CSS долей высоты хиро, но условие сформулировано
 * про ЧЕРНИЛА («слово занимает 70 % высоты блока»), а слой выше их на поле
 * для подскока. Поэтому CSS умножает свою долю на это число.
 */
export const VIEW_OVER_INK = WM_VIEW_HEIGHT / WM_BOX_HEIGHT;

/**
 * Смягчение ХИРО: сжатие начинается спокойно и доходит до края решительно.
 * Плоское с обоих концов — это верно для первого экрана, где слово стоит
 * в покое и должно трогаться мягко.
 */
export function ease(t: number): number {
  return t * t * (3 - 2 * t);
}

/**
 * СМЯГЧЕНИЯ У ФУТЕРА НЕТ, И ЭТО ТРЕБОВАНИЕ, А НЕ УПРОЩЕНИЕ.
 *
 * Футер не прилипает: секция едет обычным скроллом, слово едет вместе с ней
 * и одновременно растёт. Низ чернил стоит на месте ровно потому, что верх
 * уходит вверх со скоростью страницы, а высота растёт с той же скоростью.
 * Равенство скоростей держится только при ЛИНЕЙНОЙ связи прогресса
 * и формы: любое смягчение развело бы их, и низ поехал бы.
 *
 * Поэтому у футера e = t. Прежняя степень 1.6 (седьмая итерация) отменена
 * вместе с прилипанием — см. CLAUDE.md, Р-33.
 */
export function easeFooter(t: number): number {
  return t;
}

/**
 * ДОЛЯ СЛОЯ, занятая чернилами в СЖАТОМ состоянии. Из неё выводится ход
 * роста в футере: слово растёт от этой доли до единицы, а значит
 * ход = высота слоя × (1 − доля). Один пиксель прокрутки — один пиксель
 * прироста высоты чернил.
 */
export const WM_INK_TIGHT = WM_BOTTOM_TIGHT / WM_BOX_HEIGHT;

/**
 * ВОЗДУХ ПОД СЛОВОМ В ФУТЕРЕ, пиксели. На всём ходу роста низ чернил стоит
 * на этой высоте от нижнего края экрана. В эталоне арт-директора низ стоял
 * на 906 из 920, то есть в 14 px от края; взято 12 — ровно то же поле,
 * что отбивает слово от шапки сверху.
 */
export const FOOTER_BOTTOM_GAP = 12;

/**
 * Высота прописной по УЖЕ смягчённому ходу e (0 — раскрытое, 1 — сжатое).
 * Хиро и футер смягчают по-разному, поэтому геометрия принимает готовое
 * число: два разных смягчения не должны раздваивать формулы.
 */
export function capAtE(e: number): number {
  return WM_CAP_OPEN + (WM_CAP_TIGHT - WM_CAP_OPEN) * e;
}
export function capAt(t: number): number {
  return capAtE(ease(t));
}

/**
 * Низ чернил по смягчённому ходу e. Самая нижняя точка у обоих состояний
 * одна и та же (проверено сборкой), поэтому это ровно линейная интерполяция
 * двух чисел, а не обход массива: ошибка за весь ход — ноль. Отсюда футер
 * берёт величину, которой прижимает низ к линии.
 */
export function bottomAtE(e: number): number {
  return WM_BOTTOM_OPEN + (WM_BOTTOM_TIGHT - WM_BOTTOM_OPEN) * e;
}
export function bottomAt(t: number): number {
  return bottomAtE(ease(t));
}

/**
 * ДОЛЯ ВЫСОТЫ СЛОЯ, ЗАНЯТАЯ ЧЕРНИЛАМИ, — от 0.582 в сжатом состоянии до 1
 * в раскрытом. Верх чернил стоит на нуле, поэтому это ровно положение
 * НИЖНЕЙ КРОМКИ в долях слоя.
 *
 * Из неё выводится всё, что должно идти за кромкой: подъём текстов в хиро
 * и нижний край зелёного поля в футере. Одна величина на всех — значит
 * разъехаться на кадре нечему.
 */
export function inkAtE(e: number): number {
  return bottomAtE(e) / WM_BOX_HEIGHT;
}

/**
 * Насколько уезжают вверх тексты под словом, в долях высоты чернил.
 * Это ровно подъём нижней кромки: тексты прицеплены к ней, а не к отдельной
 * формуле от прогресса, поэтому не отстают и не обгоняют ни на одном кадре.
 */
export function footRise(t: number): number {
  return inkAtE(ease(t)) - 1;
}

const N = WM_OPEN.length;
/** Буфер точек выделяется один раз: в кадре ни одной аллокации. */
const cur = new Float32Array(N);
/** Буфер строк по литерам — тоже один раз. */
const out: string[] = WM_LETTER_CONTOURS.map(() => '');

function num(v: number): string {
  return String(Math.round(v * 1000) / 1000);
}

/**
 * Контуры слова на прогрессе t — по одной строке d на литеру.
 *
 * Слово разрезано на шесть групп, потому что вход двигает каждую литеру
 * своим трансформом. На саму форму это не влияет: точки те же и в том же
 * порядке, просто команды разложены по шести путям вместо одного.
 */
export function buildPathsE(e: number): readonly string[] {
  for (let i = 0; i < N; i += 1) cur[i] = WM_OPEN[i] + (WM_TIGHT[i] - WM_OPEN[i]) * e;
  let o = 0;
  let p = 0;
  let c = 0;
  for (let L = 0; L < WM_LETTER_CONTOURS.length; L += 1) {
    let d = '';
    for (let k = 0; k < WM_LETTER_CONTOURS[L]; k += 1) {
      const n = WM_CONTOURS[c];
      c += 1;
      d += `M${num(cur[p])} ${num(cur[p + 1])}`;
      p += 2;
      for (let i = 0; i < n; i += 1) {
        if (WM_OPS[o] === 1) {
          d += `L${num(cur[p])} ${num(cur[p + 1])}`;
          p += 2;
        } else {
          d += `Q${num(cur[p])} ${num(cur[p + 1])} ${num(cur[p + 2])} ${num(cur[p + 3])}`;
          p += 4;
        }
        o += 1;
      }
      d += 'Z';
    }
    out[L] = d;
  }
  return out;
}

/** То же от сырого хода, со смягчением хиро. */
export function buildPaths(t: number): readonly string[] {
  return buildPathsE(ease(t));
}

/** Рамка для viewBox: поле сверху, верх чернил на нуле, низ — раскрытое состояние. */
export const VIEW_BOX = `0 ${-WM_PAD} ${WM_WIDTH} ${WM_VIEW_HEIGHT}`;

/**
 * Рамка БЕЗ поля сверху — для футера.
 *
 * Поле над словом нужно только входу букв: литера перелетает выше конечного
 * положения, и без запаса перелёт срезала бы собственная рамка. Входа
 * в футере нет, значит поле там — чистый расход, который приходилось
 * компенсировать отрицательным полем самого SVG.
 *
 * С этой рамкой чернила занимают ровно бокс SVG: `height: 100%` — и верх
 * чернил совпадает с верхом слоя без единой поправки. Заодно слой получает
 * право ужиматься (на коротких экранах реквизиты не оставляют слову всей
 * высоты), а SVG ужимается вместе с ним — при фиксированной высоте
 * в единицах `--wm-h` он бы вылез из слоя и обрезался.
 */
export const VIEW_BOX_INK = `0 0 ${WM_WIDTH} ${WM_BOX_HEIGHT}`;
