/**
 * Промокод: правила кода, общие для формы оформления и сервера.
 *
 * Перенесено из Нейролавки (`src/lib/promokod.ts`) и по той же
 * причине лежит ОДНИМ файлом на обе стороны: код набирает человек
 * в форме, а находит его сервер. Две копии правил разъехались бы
 * на первой правке — форма показывала бы скидку, которой в заказе
 * нет, и заметить это можно было бы только по жалобе (Р-167).
 *
 * Отсюда всё устройство:
 *   • код приводится к `[A-Z0-9-]` и прописным: его читают с картинки
 *     или из сообщения и набирают руками, а «l» и «I» вперемешку
 *     различаются плохо. «leto-25», «LETO 25» и «Leto—25» — один код;
 *   • длина ограничена шестнадцатью знаками, как в Нейролавке;
 *   • сравнение идёт по НОРМАЛИЗОВАННОМУ виду с обеих сторон.
 *
 * ⚠️ КИРИЛЛИЦА НЕ ВЫЖИВАЕТ, как и там. В Нейролавке это требование
 * Telegram, у нас — просто тот же алфавит: «ЛЕТО» даёт пустой код,
 * то есть «кода нет», и это честнее подстановки чего-нибудь похожего.
 */

/** Сколько знаков кода принимается. */
export const PREDEL_KODA = 16;

export function kodPromo(syroe: string | null | undefined): string {
  return (syroe ?? '')
    .toUpperCase()
    .replace(/[^A-Z0-9-]+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, PREDEL_KODA)
    .replace(/-$/, '');
}

/**
 * Почему код не подошёл. Коды, а не фразы: фразу показывает форма,
 * и одна строка на двоих однажды разъехалась бы с тем, что произошло.
 */
export type OtkazPromo =
  /** Такого кода нет вовсе — или он набран с ошибкой. */
  | 'net'
  /** Срок действия кончился. */
  | 'istyok'
  /** Активации кончились: код разобрали. */
  | 'konchilis'
  /** Код отключён досрочно. */
  | 'otklyuchen'
  /** У выбранного нет цены — считать скидку не от чего. */
  | 'net_ceny'
  /** Слишком много неудачных попыток за минуту. */
  | 'chasto'
  /** Слишком много неудачных попыток за час: ждать минуту бесполезно. */
  | 'chasto_chas'
  /** Код уже держит другой неоплаченный заказ этого же человека. */
  | 'uzhe';

/**
 * Размер скидки в копейках.
 *
 * ⚠️ СЧИТАЕТСЯ ОТ ТЕКУЩЕЙ ЦЕНЫ ТАРИФА, ТО ЕСТЬ УЖЕ СО СКИДКОЙ ТАРИФА,
 * если она действует. В Нейролавке скидок тарифа нет вовсе, и правила
 * сочетания там не было; так велела постановка (Р-167). И — как там —
 * ДО баланса: иначе человек с деньгами на балансе получал бы выгоду
 * меньше объявленной, а человек с нулём — полную.
 *
 * Ноль цены — «цены нет», и скидка от неё тоже ноль.
 */
export function skidkaKop(cenaKop: number, skidkaProc: number): number {
  if (cenaKop <= 0 || skidkaProc <= 0) return 0;
  return Math.min(cenaKop, Math.round((cenaKop * skidkaProc) / 100));
}

/** Сколько остаётся после скидки промокода. Ниже нуля не бывает. */
export function posleSkidki(cenaKop: number, skidka: number): number {
  return Math.max(0, cenaKop - skidka);
}

/**
 * Объяснение отказа человеку — одно на форму и на ответ сервера.
 * Отключённый досрочно код не называется истёкшим: это была бы
 * неправда.
 */
export function otkazSlovami(pochemu: OtkazPromo): string {
  switch (pochemu) {
    case 'net':
      return 'Такого промокода нет. Проверьте, не потерялась ли буква.';
    case 'istyok':
      return 'Срок действия промокода истёк.';
    case 'konchilis':
      return 'Активации промокода кончились — его уже разобрали.';
    case 'otklyuchen':
      return 'Промокод больше не действует.';
    case 'net_ceny':
      return 'У выбранного тарифа нет цены, поэтому скидку считать не от чего.';
    case 'chasto':
      return 'Слишком много попыток. Подождите минуту и попробуйте снова.';
    case 'chasto_chas':
      return 'Слишком много попыток. Попробуйте через час или напишите в поддержку — поможем руками.';
    case 'uzhe':
      return 'Этот промокод уже применён к вашему неоплаченному заказу. Оплатите его в личном кабинете или отмените — тогда код можно будет применить снова.';
  }
}
