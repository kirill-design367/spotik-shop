/**
 * Проверка данных аккаунта: почта и пароль.
 *
 * ⚠️ ОДИН МОДУЛЬ НА КЛИЕНТ И НА СЕРВЕР, И ЭТО ОБЯЗАТЕЛЬНО. Проверка
 * нужна в обоих местах: на клиенте — чтобы человек увидел, что не так,
 * до отправки; на сервере — потому что форма это ровно то, что можно
 * переписать в браузере. Две копии правил разошлись бы на первой же
 * правке, и разошлись бы молча: сервер отказывал бы в том, что клиент
 * пропустил.
 *
 * ⚠️ ТЕКСТЫ ОТКАЗОВ ЖИВУТ ЗДЕСЬ ЖЕ. Их показывает САЙТ своим набором,
 * а не браузер всплывающей подсказкой: подсказка браузера приходит
 * системным шрифтом, на языке системы и в чужом визуальном языке.
 * Поэтому у форм снят `noValidate`-обход и проверка идёт нашей.
 */

/** Правила пароля одной строкой — она стоит ПОД полем заранее. */
export const PRAVILO_PAROLYA =
  'Не меньше 10 знаков, хотя бы одна буква и цифра или знак: # ? ! &';

/**
 * Адрес почты. Правило нарочно простое: одна собака, точка в домене,
 * ни пробелов, ни запятых. Гоняться за полным RFC незачем — настоящую
 * проверку делает письмо, которое туда уходит.
 */
export function pochtaNeVerna(v: string): string | null {
  const s = v.trim();
  if (!s) return 'Укажите почту';
  if (!/^[^\s@,;]+@[^\s@,;]+\.[^\s@,;]{2,}$/.test(s)) return 'Проверьте адрес: он должен быть вида name@pochta.ru';
  if (s.length > 200) return 'Адрес слишком длинный';
  return null;
}

/**
 * Пароль: не меньше десяти знаков, хотя бы одна буква и хотя бы одна
 * цифра или знак.
 *
 * ⚠️ БУКВА — ЛЮБАЯ, А НЕ ТОЛЬКО ЛАТИНСКАЯ. Правило про стойкость,
 * а не про раскладку; отказать человеку в кириллице значило бы
 * придумать требование, которого в постановке нет.
 */
export function parolNeGoditsya(v: string): string | null {
  if (!v) return 'Придумайте пароль';
  if (v.length < 10) return 'Пароль короче десяти знаков';
  if (!/\p{L}/u.test(v)) return 'В пароле нужна хотя бы одна буква';
  if (!/[\p{N}\p{P}\p{S}]/u.test(v)) return 'Добавьте цифру или знак: # ? ! &';
  if (v.length > 200) return 'Пароль слишком длинный';
  return null;
}

/**
 * Способ связи в обращении в поддержку: либо ник в Telegram, либо
 * почта. Ничего третьего форма не принимает — постановка.
 */
export function svyazNeVerna(v: string): string | null {
  const s = v.trim();
  if (!s) return 'Укажите ник в Telegram или почту';
  if (s.includes('@') && !s.startsWith('@')) return pochtaNeVerna(s);
  const nik = s.replace(/^https?:\/\/(t\.me|telegram\.me)\//i, '').replace(/^@/, '');
  if (/^[A-Za-z0-9_]{5,32}$/.test(nik)) return null;
  return 'Ник в Telegram (@name или ссылка t.me) либо почта';
}
