/** Рабочий день начинается в 10:00 по Москве. */
export const CHAS_OT = 10;
/** И кончается в 22:00: в 21:59 заказ ещё берут в работу. */
export const CHAS_DO = 22;

/** «10:00–22:00» — только часы, без зоны: в хиро они выделены. */
export const CHASY_OT_DO = `${String(CHAS_OT).padStart(2, '0')}:00–${CHAS_DO}:00`;
/** «10:00–22:00 по Москве» — одной строкой, для любого текста. */
export const CHASY_SLOVAMI = `${CHASY_OT_DO} по Москве`;

/** Час по Москве (0…23) для заданного момента. */
export function chasPoMoskve(kogda: Date = new Date()): number {
  try {
    const v = new Intl.DateTimeFormat('en-GB', {
      timeZone: 'Europe/Moscow',
      hour: '2-digit',
      hour12: false,
    }).format(kogda);
    const n = Number(v);
    if (Number.isFinite(n) && n >= 0 && n <= 23) return n;
  } catch {
    /* Таблицы зон в сборке нет — считаем сами, ниже. */
  }
  return (((kogda.getUTCHours() + 3) % 24) + 24) % 24;
}

/** Идёт ли сейчас рабочее время сервиса. */
export function rabocheeVremya(kogda: Date = new Date()): boolean {
  const h = chasPoMoskve(kogda);
  return h >= CHAS_OT && h < CHAS_DO;
}
