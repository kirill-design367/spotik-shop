/**
 * Канал энергии между вордмарком и волной.
 *
 * Волна и вордмарк — одна система, а не два эффекта рядом. Когда SPOTIK
 * сжимается, он отдаёт энергию в волну и та просыпается. Передавать это
 * через React-состояние нельзя: будет ре-рендер каждый кадр. Поэтому —
 * модульный изменяемый объект, который вордмарк пишет, а волна читает
 * внутри своего requestAnimationFrame.
 */
export const waveBus = {
  /** Прогресс сжатия вордмарка в хиро, 0 — раскрыт, 1 — сжат. */
  compression: 0,
  /** Прогресс разрастания вордмарка в футере, 0 — сжат, 1 — раскрыт. */
  footer: 0,
  /** Разовые импульсы от тапа/клика: {x, y} в долях холста, t — время старта. */
  impulses: [] as { x: number; y: number; born: number }[],
};

export function pushImpulse(x: number, y: number) {
  // больше восьми одновременных кругов на воде глаз всё равно не читает,
  // а кадр они съедают
  if (waveBus.impulses.length > 7) waveBus.impulses.shift();
  waveBus.impulses.push({ x, y, born: performance.now() });
}
