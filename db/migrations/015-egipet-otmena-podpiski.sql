-- Сорок девятая итерация: ЕГИПЕТ У ПАРЫ И ОТМЕНА ПОДПИСКИ.

-- ── ЕГИПЕТ ──────────────────────────────────────────────────────────
--
-- Постановка: «Для пар „тариф × срок", где аккаунт с привязкой
-- к Египту, показывай плашку… Какие пары — задаётся в админке
-- в „Ценах" галочкой „Египет" у каждой пары».
--
-- ⚠️ В ТАБЛИЦЕ ЛЕЖАТ ПАРЫ С ЕГИПТОМ, А НЕ БЕЗ НЕГО, и это обратное
-- тому, как устроены `plan_off` и `staff_plan_off`. Там «ничего
-- не сказано» обязано значить «можно» — новая пара или новый
-- оператор получают всё по построению. Здесь наоборот: Египет —
-- особый случай, и пара, о которой ничего не сказано, обычная.
-- Пустая таблица значит «плашки нет нигде», и это законное
-- состояние: администратор снял все галочки.
--
-- ⚠️ КЛЮЧ — ПАРА, А НЕ ТАРИФ, и от цены, скидки, скрытия и имени
-- тарифа галочка не зависит вовсе: она живёт своей строкой.
create table if not exists plan_egypt (
  plan_id text not null,
  period  int  not null,
  primary key (plan_id, period)
);

-- Умолчание постановки: «Индивидуальный — 3 и 6 мес; На двоих — 3,
-- 6 и 12 мес». Засыпается ОДИН РАЗ, здесь: дальше пары правит
-- администратор, и повторный прогон миграций сюда не заходит.
insert into plan_egypt (plan_id, period) values
  ('solo', 3), ('solo', 6),
  ('duo', 3), ('duo', 6), ('duo', 12)
on conflict do nothing;

-- ── ОТМЕНА ПОДПИСКИ ─────────────────────────────────────────────────
--
-- Постановка: «„Отменить" у выполненного заказа спрашивает
-- подтверждение. Затем создаётся задача „Отмена подписки" и попадает
-- в очередь тому оператору, который выполнял заказ. Если выполнял
-- администратор или оператора больше нет — в общую очередь».
--
-- ⚠️ ЗАДАЧА — СВОЯ СТРОКА, А НЕ ЕЩЁ ОДНО СОСТОЯНИЕ ЗАКАЗА. У заказа
-- уже есть держатель (`operator_id` — тот, кто его выполнил), и он
-- нужен истории; у задачи держатель свой, и он может быть другим
-- человеком. Одна колонка на двоих означала бы, что взятие задачи
-- переписывает «кто выполнил заказ».
--
-- ⚠️ ЗАДАЧА ОДНА НА ЗАКАЗ — ключ по заказу. Второй раз отменить
-- уже отменённый заказ нечем, и двух задач на одну подписку быть
-- не может по построению.
create table if not exists sub_cancel (
  order_id     bigint      primary key references shop_order (id) on delete cascade,
  -- Кто нажал «Отменить» (администратор).
  requested_by bigint      references staff (id),
  -- Держатель задачи. Пусто — общая очередь.
  operator_id  bigint      references staff (id),
  created_at   timestamptz not null default now(),
  done_at      timestamptz,
  done_by      bigint      references staff (id)
);
create index if not exists sub_cancel_otkrytye on sub_cancel (created_at) where done_at is null;

-- Отметка «подписка на этом аккаунте отменена» — шаг задачи. Шаги
-- те же, что у обычного заказа: по одному на аккаунт, и «Назад»
-- снимает самую позднюю отметку.
alter table order_slot add column if not exists sub_cancelled_at timestamptz;

-- ── ЖУРНАЛ ──────────────────────────────────────────────────────────
--
-- Постановка: «Событие пишется в журнал заказа: кто нажал „Отменить",
-- кто выполнил отмену подписки».
--
-- ⚠️ ДВА НОВЫХ ГЛАГОЛА, И «ОТМЕНИЛ» СРЕДИ НИХ НЕТ. `otmenil` считает
-- статистика по сотрудникам — «сколько заказов отменил каждый»,
-- и это отмены ДО выполнения, с возвратом денег на баланс. Отмена
-- подписки у выполненного заказа — другое действие: денег никто
-- не возвращает, а работа по заказу была сделана. Смешай их одним
-- словом — колонка «Отменил» молча поменяла бы смысл.
alter table order_event drop constraint if exists order_event_vid_check;
alter table order_event add constraint order_event_vid_check
  check (vid in ('vzyal', 'vernul', 'vypolnil', 'otmenil', 'otmena_zaproshena', 'podpiska_otmenena'));
