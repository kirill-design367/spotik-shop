-- Сорок вторая итерация: названия тарифов из админки, пошаговое
-- выполнение заказа и ссылка восстановления пароля по токену.

-- ── НАЗВАНИЯ ТАРИФОВ ───────────────────────────────────────────────────
--
-- ⚠️ ОТДЕЛЬНАЯ ТАБЛИЦА С ДВУМЯ КОЛОНКАМИ, А НЕ ПРАВКА `lib/plans.ts`.
-- Состав тарифов остаётся в коде (`DARIMYE`) — лендинг собирается
-- на раннере, где базы нет вовсе, и он обязан собраться (Р-85).
-- Имя из базы НАКЛАДЫВАЕТСЯ поверх умолчания ровно так же, как цена.
--
-- ⚠️ ДВА ИМЕНИ, И ОНИ РАЗНОГО КЛАССА. `name` — то, что видит КЛИЕНТ:
-- главная, сертификаты, оформление, кабинет, письма. `name_en` —
-- надпись для СОТРУДНИКОВ: бот и английская админка (закон 40).
-- Русское имя сотруднику тоже видно — в русской админке; английское
-- клиенту не видно нигде.
create table if not exists plan_name (
  plan_id text primary key,
  name    text not null,
  name_en text not null
);

-- ── ОФИЦИАЛЬНАЯ ДАТА ОКОНЧАНИЯ ПОДПИСКИ ────────────────────────────────
--
-- Её называет САМ SPOTIFY, и на продлении она не совпадает с «сегодня
-- плюс срок заказа»: у клиента уже был остаток. Оператор переписывает
-- её с экрана Spotify на последнем шаге, и от неё же считается письмо
-- за три дня до конца (закон 44).
--
-- ⚠️ ДАТА, А НЕ МЕТКА ВРЕМЕНИ: Spotify показывает день, и часа у этой
-- величины не существует. `shop_order.expires_at` остаётся меткой —
-- он ставится по САМОЙ РАННЕЙ из введённых дат, потому что напоминание
-- обязано уйти до того, как кончится первый из аккаунтов.
alter table order_slot add column if not exists ends_at date;

-- ── ССЫЛКА ВОССТАНОВЛЕНИЯ ПАРОЛЯ SPOTIFY ───────────────────────────────
--
-- ⚠️ В БАЗЕ ЛЕЖИТ ТОЛЬКО ОТПЕЧАТОК ТОКЕНА, как у сессии и у кода
-- сертификата (Р-87): унесённая база не открывает ни одной ссылки.
-- Токен привязан к СЛОТУ, а не к заказу: в заказе на двоих пароль
-- не подошёл у одного из аккаунтов, и страница обязана показать
-- именно его почту.
--
-- Срок жизни — семь дней с отправки письма, ровно столько же, сколько
-- живут шифротексты после закрытия заказа: позже показывать нечего,
-- потому что почта к тому времени стёрта уборкой.
create table if not exists recovery_link (
  token_fp   text        primary key,
  order_id   bigint      not null references shop_order (id) on delete cascade,
  slot_id    bigint      not null references order_slot (id) on delete cascade,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null
);
create index if not exists recovery_link_slot on recovery_link (slot_id);
