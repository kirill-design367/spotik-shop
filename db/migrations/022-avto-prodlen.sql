-- Доводка пятьдесят четвёртой итерации: новая причина отключения
-- автоплатежа — `prodlen`.
--
-- Постановка: «Ручное продление на другой срок не останавливает
-- автоплатёж — возможна двойная оплата. Любое оплаченное продление того
-- же аккаунта должно сдвигать или отключать автоплатёж так, чтобы
-- за один период не было двух списаний».
--
-- Сдвинуть можно, только когда продлён ровно тот же набор аккаунтов:
-- подписка переезжает на новый заказ. Если продлена часть набора
-- (один из двух аккаунтов «На двоих») или набор чужой (другой человек,
-- аккаунты в придачу), подписка отключается: списание за весь набор
-- оплатило бы продлённый аккаунт второй раз. Прежнее `zamenena`
-- говорит клиенту «перенесён на более новый заказ этих же аккаунтов» —
-- здесь это была бы неправда, поэтому причина своя.

alter table avtoplatezh drop constraint if exists avtoplatezh_prichina_check;
alter table avtoplatezh add constraint avtoplatezh_prichina_check
  check (prichina in ('klient', 'dve_neudachi', 'zakaz_otmenyon', 'ne_prodayotsya',
                      'admin', 'prosrochen', 'testovaya', 'zamenena', 'bez_recurring', 'prodlen'));
