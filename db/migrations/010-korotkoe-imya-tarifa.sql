-- Сорок третья итерация: КОРОТКОЕ имя тарифа — то, что стоит
-- на карточке главной и на странице сертификатов.
--
-- ⚠️ ТРЕТЬЯ КОЛОНКА, А НЕ ВТОРОЕ НАЗНАЧЕНИЕ У ПЕРВОЙ. До неё своё
-- имя из админки вставало и в полное место, и на карточку разом
-- (Р-142): второго, короткого варианта у него не было вовсе,
-- и выдумать его было неоткуда. Отсюда и открытый вопрос 99 —
-- «Для двоих» на карточке встаёт хорошо, а «Индивидуальный тариф
-- на одного человека» ужимается кеглем и на 320 px уходит в две
-- строки. Теперь коротким именем распоряжается человек.
--
-- ⚠️ ПУСТАЯ СТРОКА ЗНАЧИТ «КОРОТКОГО НЕТ», и тогда на карточку
-- встаёт полное имя — ровно то поведение, которое было до этой
-- миграции. Поэтому `default ''`, а не `null`: у величины два
-- состояния, и третьего заводить незачем (то же правило, что
-- у скидки, Р-116).
alter table plan_name add column if not exists name_short text not null default '';
