-- Тридцать четвёртая итерация: дата окончания и напоминание, скидки,
-- доступность тариф × срок, обращения в поддержку.

-- ── ДАТА ОКОНЧАНИЯ ДОСТУПА И НАПОМИНАНИЕ ───────────────────────────────
--
-- Считается при ЗАКРЫТИИ заказа: дата выполнения плюс срок тарифа.
-- Раньше знать её неоткуда — доступ ещё не выдан.
--
-- ⚠️ `reminded_at` — ЭТО ЗАЩЁЛКА, А НЕ ЖУРНАЛ. Письмо-напоминание
-- уходит ОДИН раз на заказ; будильник ходит каждый час, и без отметки
-- он слал бы его каждый час все три дня.
alter table shop_order add column if not exists expires_at  timestamptz;
alter table shop_order add column if not exists reminded_at timestamptz;

create index if not exists shop_order_expires
  on shop_order (expires_at)
  where expires_at is not null and reminded_at is null;

-- ── ОТПЕЧАТОК ПОЧТЫ УЧАСТНИКА ──────────────────────────────────────────
--
-- Нужен ровно затем, чтобы напоминание об окончании НЕ уходило туда,
-- где продление уже оформлено. Сама почта лежит шифротекстом, и AES-GCM
-- со случайным вектором двух одинаковых строк одинаковыми не делает —
-- искать по нему нельзя вовсе. Отпечаток солится ключом шифрования
-- (`otpechatokPochty`), поэтому унесённая база словарём не вскрывается.
alter table order_slot add column if not exists login_fp text;

create index if not exists order_slot_login_fp on order_slot (login_fp) where login_fp is not null;

-- ── СКИДКА НА ПАРУ ТАРИФ × СРОК ────────────────────────────────────────
--
-- ⚠️ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ КОЛОНКА В `plan_price`. Скидка живёт
-- своей жизнью: у неё есть дата окончания, после которой она снимается
-- САМА, а обычная цена остаётся на месте. Положи её в ту же строку —
-- и снятие скидки означало бы правку цены, то есть потерю той цены,
-- к которой надо вернуться.
create table if not exists plan_discount (
  plan_id   text        not null,
  period    integer     not null,
  price_kop bigint      not null,
  -- Последний день, когда скидка действует. Сравнение идёт по дате,
  -- а не по метке времени: «до 30.09» значит «включая 30 сентября».
  until     date        not null,
  primary key (plan_id, period)
);

-- ── ДОСТУПНОСТЬ ПАРЫ ТАРИФ × СРОК ──────────────────────────────────────
--
-- ⚠️ В ТАБЛИЦЕ ЛЕЖАТ ТОЛЬКО ВЫКЛЮЧЕННЫЕ ПАРЫ. «Ничего не сказано»
-- значит «доступно, если есть цена» — ровно то поведение, которое было
-- до неё: у «На троих» цена задана только на месяц, и на остальных
-- сроках он не оформляется. Заведи мы строку на каждую пару — список
-- пришлось бы чинить при добавлении тарифа или срока.
create table if not exists plan_off (
  plan_id text    not null,
  period  integer not null,
  primary key (plan_id, period)
);

-- ── ЧАСТОТА САМООБНОВЛЕНИЯ ОЧЕРЕДИ ────────────────────────────────────
--
-- ⚠️ ЗА СОТРУДНИКОМ, А НЕ ЗА БРАУЗЕРОМ — то же правило, что у языка
-- админки (Р-96): постановка требует памяти ЗА ПОЛЬЗОВАТЕЛЕМ, и выбор
-- обязан переехать с человеком на другую машину. Ноль — «выключено».
alter table staff add column if not exists queue_sec integer not null default 30;

-- ── ПОПЫТКИ ОТПРАВИТЬ ОБРАЩЕНИЕ В ПОДДЕРЖКУ ────────────────────────────
--
-- Форма ПУБЛИЧНАЯ, и за ней стоит служебный чат: без ограничения
-- частоты его завалят за час. Счётчик того же устройства, что
-- у кода сертификата (Р-107): внешнего ключа нет, строка живёт двое
-- суток и уходит уборкой.
create table if not exists support_try (
  id         bigserial   primary key,
  adres      text        not null,
  user_id    bigint,
  created_at timestamptz not null default now()
);

create index if not exists support_try_adres on support_try (adres, created_at desc);
