-- Сорок третья итерация: У КАКОГО АККАУНТА причина отмены.
--
-- ⚠️ ХРАНИМ НОМЕР, А НЕ АДРЕС, И ЭТО НЕ ПРИДИРКА. Клиенту причина
-- показывается с самим адресом («…уже зарегистрирован: почта»), и
-- первая редакция правки складывала готовую строку прямо
-- в `cancel_reason`. Так нельзя по двум причинам, и обе настоящие:
--
--   1. `cancel_reason` НЕ СТИРАЕТСЯ семидневной уборкой. Она гасит
--      пять колонок `*_enc` у слотов (`lib/server/upkeep.ts`), а
--      строка причины остаётся навсегда — то есть открытая почта
--      аккаунта Spotify пережила бы стирание и уехала бы в ночную
--      копию базы. Закон 35 ровно этому и служит.
--   2. `cancelReason` в карточке админки НЕ ЗАКРЫТ признаком `moy`,
--      в отличие от `clientLogin`: адрес в нём увидел бы любой
--      сотрудник на ЧУЖОМ заказе, а закон 35 пускает к нему только
--      оператора, который ЭТОТ заказ взял.
--
-- Поэтому в базе лежит НОМЕР СЛОТА, а адрес подставляется при
-- ЧТЕНИИ — владельцу в кабинете (он и так законный читатель своих
-- шифротекстов) и один раз при ОТПРАВКЕ письма. После стирания
-- подставлять нечего, и причина честно остаётся без адреса: мы
-- к тому времени его и правда забыли.
alter table shop_order add column if not exists cancel_slot_idx smallint;
