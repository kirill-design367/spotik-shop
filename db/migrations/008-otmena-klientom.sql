-- Кто отменил заказ: сам покупатель или оператор.
--
-- ⚠️ ЭТО НЕ ВЫВОД ИЗ `operator_id`, И ЭТО ВАЖНО. Отменённый КЛИЕНТОМ
-- заказ из кабинета исчезает совсем (постановка тридцать шестой
-- итерации), а отменённый ОПЕРАТОРОМ остаётся — с причиной и строкой
-- про деньги на балансе. Сегодня клиент отменяет только неоплаченный
-- заказ, у которого оператора и нет, — но связь эта молчаливая:
-- стоит однажды разрешить отмену взятого заказа, и карточки начнут
-- пропадать не те. Признак заведён отдельной колонкой.
--
-- Прежние строки остаются `false`: заказы, отменённые до этой правки,
-- по-прежнему видны в кабинете. Так честнее — человек их уже видел.
alter table shop_order add column if not exists cancelled_by_client boolean not null default false;
