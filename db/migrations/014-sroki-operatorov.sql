-- Сорок седьмая итерация: ГАЛОЧКИ ОПЕРАТОРОВ СТАЛИ ПО ТАРИФУ И СРОКУ.
--
-- Постановка: «Сейчас в разделе „Сотрудники" галочка стоит на тариф
-- целиком. Нужно выбирать и сроки: под каждым тарифом — галочки 1, 3,
-- 6, 12 месяцев… Уже снятые галочки тарифов переносятся на все сроки
-- этого тарифа».
--
-- ⚠️ ЗАПРЕТЫ ОСТАЛИСЬ ЗАПРЕТАМИ, И ЭТО ТА ЖЕ ПРИЧИНА, ЧТО В 013:
-- «новый оператор по умолчанию получает все тарифы и все сроки».
-- Храни мы разрешённые пары — у только что заведённого оператора
-- строк нет ни одной, то есть ему не разрешено ничего. «Ничего
-- не сказано» значит «можно» (Р-116, Р-155).
--
-- ⚠️ ЗАСЫП ИДЁТ ОДИН РАЗ, ЗДЕСЬ, А НЕ ВЫВОДИТСЯ ПРИ КАЖДОМ ЧТЕНИИ.
-- Строка без срока значила «весь тариф целиком»; выводи мы это
-- на лету, у запрета стало бы два источника — таблица и правило
-- «null значит все», — и каждый будущий читатель обязан был бы
-- помнить второй (то же рассуждение, что у истории заказов, Р-153).
-- После миграции `period` не бывает пустым никогда.
--
-- ⚠️ СПИСОК СРОКОВ ЗДЕСЬ ВЫПИСАН ЧИСЛАМИ, и это законно ровно потому,
-- что это РАЗОВЫЙ ЗАСЫП исторических строк, а не живое правило.
-- Живой источник сроков один и лежит в `lib/plans.ts` (`PERIODS`);
-- добавится пятый срок — новые операторы получат его по построению
-- («ничего не сказано значит можно»), а эта миграция к тому времени
-- давно применена и переписываться не должна.
--
-- ⚠️ ПЕРВИЧНЫЙ КЛЮЧ СНИМАЕТСЯ ДО ЗАСЫПА, А НЕ ПОСЛЕ. Он сейчас
-- (staff_id, plan_id), и вторая строка того же тарифа с другим сроком
-- нарушила бы его на первой же вставке.
alter table staff_plan_off add column if not exists period int;

alter table staff_plan_off drop constraint if exists staff_plan_off_pkey;

insert into staff_plan_off (staff_id, plan_id, period)
select s.staff_id, s.plan_id, p.period
  from staff_plan_off s
       cross join (values (1), (3), (6), (12)) as p (period)
 where s.period is null;

delete from staff_plan_off where period is null;

alter table staff_plan_off alter column period set not null;

alter table staff_plan_off add primary key (staff_id, plan_id, period);
