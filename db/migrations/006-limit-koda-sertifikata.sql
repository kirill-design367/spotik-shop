-- Попытки ввода кода сертификата.
--
-- ⚠️ ЛОЖАТСЯ СЮДА ТОЛЬКО НЕУДАЧНЫЕ ПОПЫТКИ. Честный путь зовёт
-- проверку кода ДВАЖДЫ одним и тем же верным кодом — «Проверить код»,
-- а потом «Активировать», — и у сертификата на троих к ним
-- добавляется по заходу на каждую ошибку в форме. Считай мы удачные,
-- человек упирался бы в лимит на своём же сертификате.
--
-- ⚠️ ВНЕШНЕГО КЛЮЧА НА `app_user` НЕТ НАМЕРЕННО. Это счётчик, а не
-- связь: ключ брал бы блокировку на строку пользователя при каждой
-- вставке, а вставка идёт как раз тогда, когда по нам стучат часто.
-- Строка живёт два дня и уходит уборкой.
create table if not exists cert_try (
  id         bigserial   primary key,
  -- Адрес клиента; когда заголовков нет вовсе — общая корзина.
  adres      text        not null,
  -- Учётная запись, если человек вошёл. Проверка кода открыта
  -- анонимно, поэтому здесь бывает null.
  user_id    bigint,
  created_at timestamptz not null default now()
);

create index if not exists cert_try_adres on cert_try (adres, created_at desc);
create index if not exists cert_try_user on cert_try (user_id, created_at desc) where user_id is not null;
