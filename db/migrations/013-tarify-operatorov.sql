-- Сорок шестая итерация: КАКИЕ ТАРИФЫ МОЖЕТ ВЫПОЛНЯТЬ ОПЕРАТОР.
--
-- Постановка: «Администратор выбирает галочками, какие тарифы может
-- выполнять каждый оператор… Галочки привязаны к самому тарифу,
-- а не к названию или цене. Переименование тарифа, смена цены,
-- скидки, скрытие тарифа на сайте галочки не сбрасывают. Новый
-- оператор по умолчанию получает все тарифы».
--
-- ⚠️ В ТАБЛИЦЕ ЛЕЖАТ ТОЛЬКО ЗАПРЕЩЁННЫЕ ПАРЫ, А НЕ РАЗРЕШЁННЫЕ,
-- И ЭТО ПРЯМОЕ СЛЕДСТВИЕ ТРЕБОВАНИЯ «новый оператор получает все
-- тарифы». Храни мы разрешённые — у только что заведённого оператора
-- строк нет ни одной, то есть ему не разрешено НИЧЕГО, и пришлось бы
-- заводить второй признак «его уже настраивали». «Ничего не сказано»
-- значит «можно» — ровно как в `plan_off`, где лежат только
-- выключенные пары тариф × срок (Р-116).
--
-- ⚠️ КЛЮЧ — `plan_id`, И ИМЕННО ПОЭТОМУ ГАЛОЧКИ ПЕРЕЖИВАЮТ
-- ПЕРЕИМЕНОВАНИЕ. Имя тарифа лежит в `plan_name` и правится
-- в админке (Р-142), цена — в `plan_price`, скидка — в
-- `plan_discount`, скрытие — в `plan_off`: ни одна из этих таблиц
-- сюда не смотрит, и наоборот. Состав тарифов живёт в `lib/plans.ts`
-- и от базы не зависит вовсе (см. `lib/server/catalog.ts`).
--
-- ⚠️ АДМИНИСТРАТОРА ЭТА ТАБЛИЦА НЕ КАСАЕТСЯ: «Сам администратор
-- может взять любой заказ всегда». Строки для него не пишутся,
-- и проверка до неё не доходит.
--
-- ⚠️ `on delete cascade` — чтобы удалённый сотрудник не оставлял
-- за собой мусора. Админка сотрудников не удаляет, а отключает
-- (`disabled`), и тогда запреты остаются на месте: включат обратно —
-- настройка та же, что была.
create table if not exists staff_plan_off (
  staff_id bigint not null references staff (id) on delete cascade,
  plan_id  text   not null,
  primary key (staff_id, plan_id)
);
