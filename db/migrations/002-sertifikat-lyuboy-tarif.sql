-- СЕРТИФИКАТ НА ЛЮБОЙ ТАРИФ.
--
-- До этой миграции сертификат покрывал ровно один аккаунт и имел
-- СВОЮ цену: в каталоге он стоял четвёртым тарифом с идентификатором
-- `gift`, и цену ему назначал администратор отдельной строкой.
--
-- Теперь сертификат — не тариф, а способ купить ЛЮБОЙ тариф другому
-- человеку. Цены у него нет вовсе: он стоит ровно столько, сколько
-- подаренный тариф на выбранный срок. Значит `certificate.plan_id`
-- и `shop_order.plan_id` обязаны нести НАСТОЯЩИЙ тариф, а строка
-- `gift` в таблице цен смысла больше не имеет.
--
-- ⚠️ ПОЧЕМУ 'solo', А НЕ ОТКАЗ. Прежние сертификаты продавались
-- ровно на один аккаунт, и 'solo' — это то, чем они и были. Отказать
-- в активации уже купленному сертификату нельзя: человек заплатил.

update certificate set plan_id = 'solo' where plan_id = 'gift';
update shop_order set plan_id = 'solo' where plan_id = 'gift';

alter table certificate alter column plan_id drop default;

-- Отдельной цены у сертификата больше нет, и настройки её в админке
-- тоже: строка осталась бы висеть в базе, ни на что не влияя.
delete from plan_price where plan_id = 'gift';
