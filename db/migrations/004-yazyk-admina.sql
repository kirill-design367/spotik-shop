-- Язык интерфейса админки — ЗА СОТРУДНИКОМ, а не за браузером.
--
-- Постановка: «выбор запоминается за пользователем». Кука помнила бы
-- его за устройством: сел за другую машину — снова английский.
-- Поэтому значение лежит в строке сотрудника, а кука только несёт
-- его на страницу входа, где сотрудника ещё нет.
alter table staff add column if not exists lang text not null default 'ru';
